"""M2 code generator: lowered ``Program`` -> Z80 assembly, program portion only.

Ports the XAnne-verified POC algorithms (``POC/pbas/codegen.py`` expressions,
control flow and FOR; ``POC/pbas/ui_codegen.py:168-243`` dynamic MESSAGE) onto
the frozen ``rt_*`` runtime interface of ARCHITECTURE.md D2. Generated code
never touches Rosanne directly: no ``call 003Bh``, no OS function-number
loads, no IX/IY (TESTING-STRATEGY.md A4/A5). The runtime text is appended
after this program portion by ``pbas.prg.assemble``.

Layout emitted here (container facts frozen in ARCHITECTURE.md D7/F8):
``org 4000h``, 256-byte zero prefix, ``start:`` at #4100, main-line code, a
final ``jp rt_exit`` so procedures are never fallen into, one ``sub_NAME``
routine per procedure, then data sections: literal pool, static MESSAGE
definition blocks, FOR loop-limit cells, variable storage in declaration
order.

String destinations (M2.1, LANGUAGE-SPEC.md section 4): every string build
first sets the runtime's active destination limit ``rt_dst_end`` (the last
byte of the destination, reserved for its NUL) and DE, then appends its parts
through the guarded runtime routines (``rt_str_copy`` / ``rt_append_int``,
both writing via ``rt_put``), then stores the NUL at DE. Overflow that is
certain at compile time is rejected by semantics; anything else that does not
fit raises the runtime string-overflow error, reporting the source line held
in ``rt_err_line``. Nothing is truncated and nothing is written past a
destination.

Dialogs (M3a, ARCHITECTURE.md D1/D3): a program with a WINDOW is the same
program with a different ending. Its main line runs exactly as above; instead
of ``jp rt_exit`` it ends with ``ld hl,gui_dialog`` / ``ld de,gui_handlers``
/ ``jp rt_gui_run``. The dialog definition and the handler table are data
built by ``pbas.layout``; the runtime owns the event loop and dispatches
clicks through the table to the ordinary ``sub_NAME`` routines, whose bodies
are generated by the same statement emitter as the main line.

Files (M4, LANGUAGE-SPEC.md section 7): FILESAVE builds its value in the
runtime file buffer through the guarded writer, then calls ``rt_file_save``
with a file descriptor (stem NUL, extension NUL); FILELOAD calls
``rt_file_load`` with the descriptor, the destination variable and its
capacity. The drive and folder are program data (``PB_FILE_DEVICE``,
``pb_file_path``) from the build options (``pbas.files``). A TEXTBOX-bound
destination needs nothing extra: the M3b binding sync redraws it when the
handler returns (or defines it when the window opens).

Unsupported-at-this-milestone constructs fail loudly with a positioned
SourceError naming the milestone (LANGUAGE-SPEC.md section 8): substring of
a computed string -> M5.
"""
