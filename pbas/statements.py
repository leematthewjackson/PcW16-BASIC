# Runtime-owned string destinations (runtime/runtime.z80.asm): alert text is
# built in rt_alert_buf (ALERT_BUFFER_SIZE text bytes before the tail);
# computed operands in 128-byte scratch buffers. M5a: the scratch buffers form
# one pool, allocated last-in-first-out by nesting depth; the first two are
# the M2 buffers (always present), the rest are assembled only when a program
# needs them (PB_STR_TEMPS). A string expression nested deeper than the pool
# is a positioned compile error.
SCRATCH_BUFFERS = ("rt_cmp_buf1", "rt_cmp_buf2")  # 128 bytes each
SCRATCH_POOL = SCRATCH_BUFFERS + ("rt_str_tmp3", "rt_str_tmp4", "rt_str_tmp5", "rt_str_tmp6")
_STRING_FUNCTIONS = ("STR$", "LEFT$", "MID$", "RIGHT$", "CHR$", "UCASE$", "LCASE$",
                     "TRIM$", "LTRIM$", "RTRIM$", "SPACE$", "STRING$",  # M7
                     "TEXTGET$")  # M9
# M5b/M5c runtime sections, each assembled only when a program uses it.
RUNTIME_FEATURES = ("DIV", "VAL", "ASC", "CHR", "INSTR", "CASE", "ARRAYS",
                    "IMATH", "STRFN", "FIO", "REAL", "BANK",  # M7, M8
                    "TEXT", "FNAME",  # M9
                    "RECORDS", "DB", "TXRANGE",  # M10
                    "TEXTW", "CLOCK",  # M11 corrective: TEXTWIDTH, SECONDS
                    "BITMAP", "BMPFILE", "POINT",  # M12 bitmaps
                    "PAGE",  # M12 printing
                    "BMPPART",  # M13: parts of bitmaps, masks
                    "KEYDOWN",  # M13: held keys
                    "CLOCKTICKS",  # M13 corrective: the clock in 1/16 s
                    "TICKPOLL",  # M13 responsiveness: TIMER EVERY n TICKS run by the event loop
                    "CKCAL",  # M13 responsiveness: CLOCKTICKS counted from the seconds' change
                    "FSAFE",  # M14: file-safety corrections to DB / BITMAP SAVE and DB LOAD
                    "RSTICKY")  # M14: REAL + and - correctly rounded (sticky bit)

# rt_compare_signed / rt_str_compare return A in {0: DE<HL, 1: equal, 2: DE>HL};
# a comparison is true when A is one of the operator's "wanted" values.
_WANTED: dict[str, tuple[int, ...]] = {
    "=": (1,),
    "==": (1,),
    "<>": (0, 2),
    "<": (0,),
    "<=": (0, 1),
    ">": (2,),
    ">=": (1, 2),
}


def generate(program: Program, location: FileLocation | None = None) -> str:
    """Emit the program portion of the assembly for *program*.

    *location* is where FILESAVE/FILELOAD files live (build options
    ``--drive``/``--folder``; default floppy ``\\PCW\\FOLDER01``).
    """
    return generate_parts(program, location).text


class GeneratedProgram:
    """M9: the program portion and where its procedures lie in it.

    ``text`` is exactly what :func:`generate` returns. ``lines`` is the same
    text split into the generator's lines (``text`` is ``"\\n".join(lines)``
    plus the ``PB_*`` switches); ``spans`` lists ``(symbol, first, end, line)``
    for every procedure in source order: line indices into ``lines`` and
    the SUB/FUNCTION's source line;
    each starts with its ``sub_SYMBOL:`` line and ends with its ``ret``.
    The procedures are contiguous, after the main line and before the data.
    """

    def __init__(self, text: str, lines: list[str], spans: list[tuple[str, int, int, int]], tail: str):
        self.text = text
        self.lines = lines
        self.spans = spans
        self.tail = tail


def generate_parts(program: Program, location: FileLocation | None = None, *,
                   legacy_menu_hotkeys: bool = False,
                   legacy_timing: bool = False,
                   legacy_file_safety: bool = False,
                   legacy_real_rounding: bool = False) -> GeneratedProgram:
    """As :func:`generate`, keeping the procedure boundaries (M9).

    *legacy_menu_hotkeys* (M13 corrective): give a menu ITEM without KEY the
    hotkey word #0000, as up to M13's first owner build, which Rosanne's
    hotkey search takes for the end of its title (``NO_HOTKEY``). Only for
    rebuilding executables the owner has accepted, byte for byte.

    *legacy_timing* (M13 responsiveness): time as in the M13 corrective
    builds: TIMER ... EVERY n TICKS a Rosanne timer (os_set_timer) instead
    of the event loop's own (PB_TICKPOLL, TICK_POLL_MAX), and CLOCKTICKS
    the raw ticks byte instead of the sixteenths since the seconds changed
    (PB_CKCAL). Only to rebuild those executables byte for byte and to show
    what the owner saw.

    *legacy_file_safety* (M14): leave out PB_FSAFE, the M14 corrections to
    DB SAVE, BITMAP SAVE and DB LOAD (runtime rt_db_own, rt_db_s_steps,
    rt_db_load). Only to rebuild executables accepted before M14 byte for byte.

    *legacy_real_rounding* (M14): leave out PB_RSTICKY, so that REAL + and -
    drop the bits shifted below the guard byte, as up to M13 (a result just
    under half a unit in the last place could round the wrong way). Only to
    rebuild executables accepted before M14 byte for byte.
    """
    windows = list(program.windows or [])
    if not windows and program.dialog_title is not None:
        line, column = program.dialog_position or (1, 1)
        windows = [WindowDecl(None, program.dialog_title, False, program.widgets, line, column)]
    menus = bool(program.menus)
    layouts = [build_dialog(program, w, menus) for w in windows]
    layout = layouts[0] if layouts else None
    gen = _Generator(program, layout, location or FileLocation(), layouts, windows)
    gen.legacy_menu_hotkeys = legacy_menu_hotkeys
    gen.legacy_timing = legacy_timing
    gen.legacy_file_safety = legacy_file_safety
    gen.legacy_real_rounding = legacy_real_rounding
    text = gen.compile()
    return GeneratedProgram(text, list(gen.w.lines), list(gen.proc_spans), gen.tail_text)


# M13 responsiveness: TIMER ... EVERY n TICKS with n up to this is run by the
# event loop on CLOCKTICKS (runtime rt_tick_poll), not by a Rosanne timer;
# the loop's arithmetic works on the clock's minute (960 sixteenths) and
# needs an interval of at most a quarter of it.
TICK_POLL_MAX = 240
MAX_NUMBERBOXES = 16  # runtime rt_num_shadow holds 16 words (M6)
MAX_SLIDERS = 16  # runtime rt_sl_value holds 16 words (M6 Phase 2)
# os_alert keys for ASK buttons (CONSTBIO): the first answers to Return and
# Green, the last to Stop and Red (shift state #80 = ignored).
# M13 corrective: the hotkey word of a menu ITEM without KEY. Rosanne's
# hotkey search (PCW045.SYS block 6 #7446, static) reads a title's hotkey
# words up to a #0000 and then goes on to the next title, so a #0000 for an
# item in the middle of a title ended that title's search and shifted every
# later hotkey into the wrong title (owner XAnne: PAINT II Ctrl+Z/Y/C/V/Q,
# DESIGNER Ctrl+D/F did nothing; Ctrl+N/O/S, before the first item without
# KEY, worked). No key produces this word: shift-state bits 3 and 5..7 are
# reserved (ROSAN283 "The Keyboard"), and the search compares whole words.
NO_HOTKEY = bytes((0x00, 0xFF))
ASK_FIRST_KEYS = bytes((0x0D, 0x80, 0xFB, 0x80, 0, 0, 0, 0))
ASK_LAST_KEYS = bytes((0xFE, 0x80, 0xFC, 0x80, 0, 0, 0, 0))


def _uses(program: Program, kinds) -> bool:
    bodies = [program.main] + [proc.body for proc in program.procedures]
    return any(isinstance(item, kinds) for body in bodies for item in _body_items(body))


def _uses_ask(program: Program) -> bool:
    bodies = [program.main] + [proc.body for proc in program.procedures]
    return any(
        isinstance(item, ast.Assign) and isinstance(item.value, ast.Call) and item.value.name == "ASK"
        for body in bodies for item in _body_items(body)
    )


def _body_items(items):
    """Every body item in *items*, including those nested in blocks."""
    for item in items:
        yield item
        if isinstance(item, IfBlock):
            yield from _body_items(item.then_body)
            yield from _body_items(item.else_body)
        elif isinstance(item, (WhileBlock, ForBlock)):
            yield from _body_items(item.body)


def _crc16(data: bytes) -> int:
    """CRC-16/CCITT-FALSE (poly #1021, initial #FFFF)."""
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else crc << 1
            crc &= 0xFFFF
    return crc


def _db_signature(variables, name: str) -> tuple[int, str]:
    """M10: (CRC-16, text) of record array *name*'s canonical field list
    (pbas/records.py Layout.signature: "ID:I;NAME:S40;…"), stored in a
    database's header so a file of another TYPE is refused (§5.9)."""
    fields = sorted((v.alias[1], n.split('%', 1)[1], v) for n, v in variables.items()
                    if getattr(v, "alias", None) is not None and v.alias[0] == name)
    parts = []
    for _, fname, v in fields:
        code = {"INTEGER": "I", "REAL": "R", "BOOLEAN": "B"}.get(v.type) or f"S{v.capacity - 1}"
        parts.append(f"{fname}:{code}")
    text = ";".join(parts)
    return _crc16(text.encode("ascii")), text


def _db_strings(variables, name: str) -> list[tuple[int, int]]:
    """M14: (offset, capacity) of each STRING field of record array *name*,
    the bytes a field may use with its terminating 0."""
    return sorted((v.alias[1], v.capacity) for n, v in variables.items()
                  if getattr(v, "alias", None) is not None and v.alias[0] == name
                  and v.type not in ("INTEGER", "REAL", "BOOLEAN"))


def uses_files(program: Program) -> bool:
    """True if *program* contains FILESAVE or FILELOAD anywhere."""
    bodies = [program.main] + [proc.body for proc in program.procedures]
    return any(
        isinstance(item, (ast.Filesave, ast.Fileload, ast.OpenFile, ast.CloseFile, ast.PrintFile,
                          ast.LineInput, ast.Kill, ast.NameFile))  # M7 sequential files
        or (isinstance(item, ast.TextOp) and item.op in ("LOAD", "SAVE"))  # M9 TEXT files
        or isinstance(item, ast.DbOp)  # M10 databases (IOERR, file names)
        or (isinstance(item, ast.BitmapOp) and item.op in ("LOAD", "SAVE"))  # M12 bitmap files
        or isinstance(item, ast.PageOp)  # M12 printing: IOERR is the file part's
        for body in bodies
        for item in _body_items(body)
    ) or any(getattr(v, "type", None) == "TEXT" for v in program.variables.values()
             ) or _calls(program, ("PAGEWIDTH",))
    # M10 (KI-52): the TEXT part refers to the file part even when the program
    # never loads or saves (it did not assemble before)
    # M14 (D14): so does the PAGE part, which PAGEWIDTH needs even in a program
    # with no PAGE statement (it did not assemble: rt_fio_set undefined)


def _calls(program: Program, names) -> bool:
    """M14: True if a call of a built-in in *names* appears anywhere (in any expression)."""
    stack = list(program.main) + [s for proc in program.procedures for s in proc.body]
    while stack:
        node = stack.pop()
        if isinstance(node, ast.Call) and node.name in names:
            return True
        if dataclasses.is_dataclass(node):
            for f in dataclasses.fields(node):
                value = getattr(node, f.name)
                if isinstance(value, (list, tuple)):
                    stack.extend(v for v in value if dataclasses.is_dataclass(v))
                elif dataclasses.is_dataclass(value):
                    stack.append(value)
    return False


class _Generator:
    def __init__(
        self,
        program: Program,
        layout: DialogLayout | None = None,
        location: FileLocation | None = None,
        layouts: list[DialogLayout] | None = None,
        windows: list[WindowDecl] | None = None,
    ) -> None:
        self.program = program
        self.legacy_menu_hotkeys = False  # M13 corrective: see generate_parts
        self.legacy_timing = False  # M13 responsiveness: see generate_parts
        self.legacy_file_safety = False  # M14: see generate_parts
        self.legacy_real_rounding = False  # M14: see generate_parts
        self.uses_fsafe = False  # M14: DB LOAD, DB SAVE or BITMAP SAVE (PB_FSAFE)
        self.layout = layout
        self.layouts = layouts if layouts is not None else ([layout] if layout else [])
        self.windows = windows or []
        rows = [r for lay in self.layouts for r in lay.bindings]
        # M6 Phase 1 features (LANGUAGE-SPEC 5.1); each selects a runtime part.
        self.p1 = {
            "RADIO": any(r.kind == BIND_RADIO for r in rows),
            "NUMBERS": any(r.kind == BIND_NUMBER for r in rows),
            "SPIN": any(r.kind == BIND_NUMBER and r.spinner for r in rows),
            "MENUS": bool(program.menus),
            "TIMER": program.timer is not None,
            "WINDOWS": any(w.name is not None for w in self.windows),
            "FOCUS": _uses(program, ast.Focus),
            "ASK": _uses_ask(program),
            "BEEP": _uses(program, ast.Beep),
        }
        self.p1["POST"] = self.p1["MENUS"] or self.p1["WINDOWS"] or self.p1["FOCUS"]
        # M6 Phase 2 parts (LANGUAGE-SPEC 5.2): lists, drop-down choices,
        # sliders, the shared scroll rule and CHANGE / ACTION handlers.
        kinds = {r.kind for r in rows}
        p2_rows = [r for r in rows if r.kind in (BIND_LIST, BIND_CHOICE, BIND_SLIDER)]
        self.p2 = {
            "LIST": BIND_LIST in kinds,
            "CHOICE": BIND_CHOICE in kinds,
            "SLIDER": BIND_SLIDER in kinds,
            "SCROLL": bool(kinds & {BIND_LIST, BIND_SLIDER}),
            "CTL2": bool(p2_rows),
            "CHANGE": any(r.widget.change or r.widget.action for r in p2_rows),
        }
        # M9: the window holding the program's CANVAS (index, layout), if any
        self.canvas = next(((i, lay) for i, lay in enumerate(self.layouts) if lay.canvas), None)
        # The Phase 1 and 2 dialog parts run inside the binding machinery
        # (M9: so do canvas handlers, which need rt_gui_after).
        self.bindings_on = bool(rows) or self.canvas is not None or any(
            self.p1[k] for k in ("POST", "MENUS", "TIMER", "RADIO", "NUMBERS"))
        sliders = [r for r in rows if r.kind == BIND_SLIDER]
        if len(sliders) > MAX_SLIDERS:
            extra = sliders[MAX_SLIDERS]
            raise SourceError(extra.line, 1, f"a program may have at most {MAX_SLIDERS} SLIDERs")
        self.slider_index = {id(r): i for i, r in enumerate(sliders)}
        numbers = [r for r in rows if r.kind == BIND_NUMBER]
        if len(numbers) > MAX_NUMBERBOXES:
            extra = numbers[MAX_NUMBERBOXES]
            raise SourceError(extra.line, 1,
                              f"a program may have at most {MAX_NUMBERBOXES} NUMBERBOXes")
        self.shadow_index = {id(r): i for i, r in enumerate(numbers)}
        self.asks: list[tuple[str, list[str]]] = []  # (label, captions)
        self.static_alerts: list[tuple[str, str]] = []  # (label, text), M6 NUMBERBOX
        self.location = location or FileLocation()
        self.w = AsmWriter()
        self.loop_limits: list[str] = []
        self.static_messages: list[tuple[str, str]] = []  # (label, text)
        self.file_names: dict[str, str] = {}  # upper-case 8.3 name -> label
        self.scratch_held: list[str] = []  # M5a scratch pool, in use (LIFO)
        self.scratch_extra = 0  # pool buffers beyond the two M2 ones ever used
        self.uses_slice = False  # M5a run-time substring arguments (PB_SLICE)
        self.uses_cv_line = False  # M9 KI-49: DRAW LINE draws sloped lines as runs (PB_CVLINE)
        self.uses_cv_cell = False  # M11: DRAW TEXT with a cell width (PB_CVCELL)
        self.db_arrays: set[str] = set()  # M10: record arrays used as databases (cgdb_ tables)
        self.features: set[str] = set()  # M5b: RUNTIME_FEATURES used
        self.loops: list[tuple[str, str]] = []  # M7: open loops (kind, end label)
        self.real_consts: dict[bytes, str] = {}  # M7: packed REAL literal -> label
        self.proc_spans: list[tuple[str, int, int, int]] = []  # M9: (symbol, first, end, source line)

    # ------------------------------------------------------------- top level
    def compile(self) -> str:
        body = self._compile_body()
        # Assembled-section switches known only after the body is generated
        # (M5a): extra scratch buffers and the run-time substring routines.
        # They follow the program portion; the runtime that tests them is
        # appended after it.
        tail = AsmWriter()
        tail.emit(f"PB_STR_TEMPS equ {self.scratch_extra}",
                  f"PB_SLICE equ {1 if self.uses_slice else 0}")
        if "IMATH" in self.features:  # M7: rt_rnd uses rt_mod16
            self.features.add("DIV")
        if "TEXT" in self.features:  # M10 (KI-52): TEXT LOAD / SAVE code uses the FIO part
            self.features.add("FIO")
        timer = self.program.timer
        if (timer is not None and timer.ticks and timer.seconds <= TICK_POLL_MAX
                and not self.legacy_timing):  # M13 responsiveness: the loop's own timer
            self.features.update(("TICKPOLL", "CLOCKTICKS"))
        if "CLOCKTICKS" in self.features and not self.legacy_timing:
            self.features.add("CKCAL")
        if "REAL" in self.features and not self.legacy_real_rounding:
            self.features.add("RSTICKY")  # M14: REAL + and - correctly rounded
        if self.uses_fsafe and not self.legacy_file_safety:
            self.features.add("FSAFE")  # M14: DB / BITMAP SAVE and DB LOAD corrections
        for name in RUNTIME_FEATURES:
            tail.emit(f"PB_{name} equ {1 if name in self.features else 0}")
        # M5d: dynamic labels in the binding table; the DEFAULT button's key.
        labels = self.layout is not None and any(r.kind == BIND_LABEL for r in self.layout.bindings)
        labels = labels or any(r.kind == BIND_LABEL for lay in self.layouts for r in lay.bindings)
        keys = any(w.kind == "BUTTON" and (w.default or w.keys)
                   for win in self.windows for w in win.widgets) or any(
            w.kind == "BUTTON" and w.default for w in self.program.widgets)
        tail.emit(f"PB_LABELS equ {1 if labels else 0}", f"PB_KEYS equ {1 if keys else 0}")
        tail.emit(f"PB_CANVAS equ {0 if self.canvas is None else 1}")  # M9
        tail.emit(f"PB_CVLINE equ {1 if self.uses_cv_line else 0}")  # M9 KI-49
        tail.emit(f"PB_CVCELL equ {1 if self.uses_cv_cell else 0}")  # M11
        # M6 Phase 1 runtime parts (LANGUAGE-SPEC 5.1)
        for name, on in self.p1.items():
            tail.emit(f"PB_{name} equ {1 if on else 0}")
        # M6 Phase 2 runtime parts (LANGUAGE-SPEC 5.2)
        for name, on in self.p2.items():
            tail.emit(f"PB_{name} equ {1 if on else 0}")
        self.tail_text = tail.render()
        return body + self.tail_text

    def _compile_body(self) -> str:
        w = self.w
        # PB_DIALOG selects the runtime's dialog/event section (IF PB_DIALOG).
        w.emit(f"PB_DIALOG equ {0 if self.layout is None else 1}")
        # PB_BINDINGS selects the runtime's control-binding section (M3b).
        w.emit(f"PB_BINDINGS equ {1 if self.layout is not None and self.bindings_on else 0}")
        # PB_FILES selects the runtime's file section (M4); PB_FILE_DEVICE is
        # the os_set_device number of the program's drive (1 = floppy).
        files = uses_files(self.program)
        w.emit(f"PB_FILES equ {1 if files else 0}")
        if files:
            w.emit(f"PB_FILE_DEVICE equ {self.location.device}")
        w.emit("    org 4000h", "    defs 100h", "start:")
        banked = [v for v in self.program.variables.values()
                  if getattr(v, "banked", False) or v.type in ("TEXT", "BITMAP")]  # M9: TEXT; M12: BITMAP
        if banked:  # M8: the BANKED arrays' blocks, before anything else runs
            self.features.update(("BANK", "ARRAYS"))
            w.emit(f"    ld hl,{banked[0].line}", "    ld (rt_err_line),hl", "    call rt_bank_init")
        for name, var in self.program.variables.items():  # M12: a new bitmap is white
            if var.type == "BITMAP":
                w.emit(f"    ld hl,var_{mangle(name)}", "    call rt_bmp_white")
        for item in self.program.main:
            self.statement(item)
        if self.layout is None:
            w.emit("    jp rt_exit")  # END: never fall through into procedures
        else:
            # Main line done: open the dialog and serve events (never returns).
            if self.p1["MENUS"]:
                w.emit("    call rt_menu_init")
            if self.p1["TIMER"]:
                w.emit("    call rt_timer_start")
            if self.p1["WINDOWS"]:
                w.emit("    ld hl,gui_windows", "    jp rt_win_start")
            else:
                if self.bindings_on:
                    w.emit("    ld hl,gui_bindings", "    ld (rt_gui_bindings),hl")
                w.emit("    ld hl,gui_dialog", "    ld de,gui_handlers", "    jp rt_gui_run")
        for proc in self.program.procedures:
            first = len(w.lines)
            w.emit("", f"sub_{mangle(proc.name)}:")
            for item in proc.body:
                self.statement(item)
            w.emit("    ret")
            # M9: where each procedure lies in the program text, for the
            # code-bank linker (pbas/codebanks.py); no effect on the output.
            self.proc_spans.append((mangle(proc.name), first, len(w.lines), proc.line))
        self._data_sections()
        return self.w.render()

    def _data_sections(self) -> None:
        w = self.w
        for label, data in w.pool_items():
            w.emit(f"{label}: db " + ",".join(str(b) for b in data))
        for data, label in self.real_consts.items():  # M7 REAL literals
            w.emit(f"{label}: db " + ",".join(str(b) for b in data))
        for label, text in self.static_messages:
            # os_alert definition format (ROSAN283.DOC 'os_alert', POC-proven in
            # NOTES.asm): NUL-terminated line(s), extra NUL, button count,
            # 4 key words, NUL-terminated button text.
            bs = list(text.encode("utf-8"))
            head = ",".join(str(b) for b in bs)
            first = f"{label}: db {head + ',' if head else ''}0,0,1"
            w.emit(first, "    dw 800Dh,80FBh,0,0", "    db 79,75,0", f"{label}_end:")
        for label in self.loop_limits:
            w.emit(f"{label}: dw 0")
        if self.layout is not None:
            for index, layout in enumerate(self.layouts):
                self._dialog_data(layout, index)
            self._phase1_data()
            self._canvas_data()
        for label, text in self.static_alerts:
            bs = ",".join(str(b) for b in text.encode("ascii"))
            w.emit(f"{label}: db {bs},0,0,1", "    dw 800Dh,80FBh,0,0", "    db 79,75,0", f"{label}_end:")
        for label, captions in self.asks:
            w.emit(f"{label}:", f"    db {len(captions)}")
            for i, caption in enumerate(captions):
                keys = ASK_FIRST_KEYS if i == 0 else ASK_LAST_KEYS if i == len(captions) - 1 else bytes(8)
                w.emit("    db " + ",".join(str(b) for b in keys + caption.encode("ascii") + b"\0"))
            w.emit(f"{label}_end:")
        fsafe = self.uses_fsafe and not self.legacy_file_safety
        for name in sorted(self.db_arrays):  # M10: database tables (runtime "databases")
            sig = _db_signature(self.program.variables, name)
            # M14 (PB_FSAFE): and the record's STRING fields, which DB LOAD checks
            strs = f",cgdbs_{mangle(name)}" if fsafe else ""
            w.emit(f"    ; database {name}: TYPE signature {sig[1]!r}",
                   f"cgdb_{mangle(name)}: dw cgbank_{mangle(name)},{sig[0]},cgdbid_{mangle(name)}{strs}",
                   f"cgdbid_{mangle(name)}: defs 2")
            if fsafe:
                fields = _db_strings(self.program.variables, name)
                w.emit(f"cgdbs_{mangle(name)}: db {len(fields)}",
                       *(line for offset, capacity in fields for line in (f"    dw {offset}", f"    db {capacity}")))
        if self.file_names or uses_files(self.program):  # M9: or only STRING names
            # os_set_cwd path (ROSAN283: 0-terminated; copied to the bottom
            # quarter by the runtime) and one descriptor per file name.
            path = self.location.folder.encode("ascii") + b"\0"
            w.emit(f"    ; file folder {self.location.folder!r} on {self.location.drive}",
                   "pb_file_path: db " + ",".join(str(b) for b in path))
            for name, label in self.file_names.items():
                w.emit(f"    ; file {name}",
                       f"{label}: db " + ",".join(str(b) for b in descriptor_bytes(name)))
        w.emit("")
        banked = [(n, v) for n, v in self.program.variables.items()
                  if getattr(v, "banked", False) and getattr(v, "alias", None) is None]  # M10: not fields
        texts = [(n, v) for n, v in self.program.variables.items() if v.type == "TEXT"]  # M9
        bitmaps = [(n, v) for n, v in self.program.variables.items() if v.type == "BITMAP"]  # M12
        if bitmaps:
            self.features.update(("BITMAP", "BANK"))
        # M14 (D2): a bitmap statement on a parameter switches the bank part on even with no
        # banked data (the procedure cannot be called then: no BITMAP exists to pass); the
        # part needs its tables to assemble, with no blocks.
        if banked or texts or bitmaps or "BANK" in self.features:  # M8: descriptors (count, size, per block, first slot) and windows
            slot = 0
            wsize = 2
            for name, var in banked:
                size, per_block, blocks = banked_layout(var)
                w.emit(f"    ; BANKED array {name}({var.length}): {blocks} block(s) of {per_block} elements",
                       f"cgbank_{mangle(name)}: dw {var.length},{size},{per_block}", f"    db {slot}")
                slot += blocks
                wsize = max(wsize, size)
            for name, var in texts:  # M9: the buffer record (runtime "TEXT buffers")
                blocks = -(-var.text_bytes // 16384)
                w.emit(f"    ; TEXT buffer {name}: {var.text_bytes} bytes in {blocks} block(s) from slot {slot}",
                       f"var_{mangle(name)}: dw {var.text_bytes}", f"    db {slot},{blocks}",
                       f"    dw 0,{var.text_bytes},1", "    db 0,0", "    dw 1,0,0")
                slot += blocks
            for name, var in bitmaps:  # M12: the bitmap record (runtime "bitmaps")
                bw, bh = var.bitmap_size
                w.emit(f"    ; BITMAP {name}: {bw} x {bh} pixels at most, block slot {slot}",
                       f"var_{mangle(name)}: dw {(bw + 7) // 8 * bh}", f"    db {slot},0",
                       f"    dw {bw},{bh}")
                slot += 1
            w.emit(f"cgbank_need equ {slot}", f"cgbank_wsize equ {wsize}",
                   f"cgbank_win: defs {max(4 * wsize, 256)}", f"cgbank_wwin: defs {wsize}")
        for name, var in self.program.variables.items():
            alias = getattr(var, "alias", None)
            if alias is not None:  # M10: a record field shares its record's storage
                parent, offset, stride = alias
                if var.banked:
                    continue  # reached through the record's BANKED descriptor (_elem_addr)
                if var.length is not None:
                    w.emit(f"cgarr_{mangle(name)}: dw {var.length},{stride},var_{mangle(parent)}+{offset}")
                else:
                    w.emit(f"var_{mangle(name)} equ var_{mangle(parent)}+{offset}")
                continue
            if getattr(var, "banked", False) or var.type in ("TEXT", "BITMAP"):  # M12: BITMAP records above
                continue
            if var.type == "RECORD" and var.length is None:  # M10: one record, zeroed
                w.emit(f"    ; record {name} of TYPE {var.record}: {var.capacity} bytes",
                       f"var_{mangle(name)}: defs {var.capacity}")
                continue
            if getattr(var, "length", None) is not None:  # M6 Phase 2: an array
                size = var.capacity if var.type in ("STRING", "RECORD") else 5 if var.type == "REAL" else 2
                w.emit(f"    ; array {name}({var.length}): descriptor (count, element size, base)",
                       f"cgarr_{mangle(name)}: dw {var.length},{size},var_{mangle(name)}",
                       f"var_{mangle(name)}: defs {size * var.length}")
            elif var.type == "STRING":
                w.emit(f"var_{mangle(name)}: defs {var.capacity}")
            elif var.type == "REAL":  # M7: 5 bytes, initially 0.0 (exponent 0)
                w.emit(f"var_{mangle(name)}: defs 5")
            else:
                w.emit(f"var_{mangle(name)}: dw 0")

    def _canvas_data(self) -> None:
        """M9: the CANVAS descriptor (runtime "CANVAS" part) and the text
        fields of its window."""
        if self.canvas is None:
            return
        index, layout = self.canvas
        number, sx, sy, width, height, widget = layout.canvas
        window = index + 1 if self.p1["WINDOWS"] else 0

        def handler(name):
            return f"sub_{mangle(name)}" if name else "0"

        edits = [o.number for o in layout.objects if o.kind in ("TEXTBOX", "NUMBER")]
        self.w.emit("    ; CANVAS: screen x, y, width, height; PAINT, MOUSE, KEYS; frame, window",
                    f"cgcanvas: dw {sx},{sy},{width},{height}",
                    f"    dw {handler(widget.paint)},{handler(widget.mouse)},{handler(widget.keys_handler)}",
                    f"    db {number},{window}",
                    "cgcv_edits: db " + ",".join(str(n) for n in [len(edits)] + edits))

    def draw(self, item: ast.Draw) -> None:
        """M9 DRAW: the arguments into rt_dw_args (words), then the routine."""
        w = self.w
        w.emit(f"    ld hl,{item.line}", "    ld (rt_err_line),hl")
        if item.op == "LINE":
            self.uses_cv_line = True
        if item.op == "INK":
            # `ld (hl),n`, not `ld a,n`, as for SHOW (asmcheck A4)
            w.emit("    ld hl,rt_dw_ink", f"    ld (hl),{('BLACK', 'WHITE', 'XOR').index(item.ink)}")
            return
        numbers = item.values[:2] + item.values[3:] if item.op == "TEXT" else item.values
        for i, value in enumerate(numbers):
            self.expr(value)
            w.emit(f"    ld (rt_dw_args+{2 * i}),hl")
        if item.op == "FILL" and len(item.values) == 4:
            w.emit("    ld hl,0", "    ld (rt_dw_args+8),hl")  # default shade: black
        if item.op == "TEXT":
            buf = self._string_ptr(item.values[2])
            if len(item.values) == 4:  # M11: each character in a cell of the given width
                self.uses_cv_cell = True
                w.emit("    call rt_draw_cells")
            else:
                w.emit("    call rt_draw_text")
            if buf is not None:
                self._scratch_release(buf)
            return
        w.emit(f"    call rt_draw_{item.op.lower()}")

    def _dialog_data(self, layout: DialogLayout | None = None, index: int = 0) -> None:
        """Emit the os_dialog_define bytes and the handler table (D3).

        M6: one set per window; the first keeps the M3a labels (gui_dialog,
        gui_handlers, gui_bindings, gui_tpl_N), window k > 1 uses gui_wk_.
        """
        w = self.w
        layout = layout or self.layout
        p = "gui_" if index == 0 else f"gui_w{index + 1}_"
        title = self.windows[index].title if self.windows else self.program.dialog_title
        definition = layout.definition
        w.emit(f"{p}dialog:")
        offset = 4 + 9 + len(title) + 1
        w.emit("    ; global: focus, exit-by-click, screen-store, ddm_enable",
               "    db " + ",".join(str(b) for b in definition[:4]),
               f"    ; box and title: {title!r}",
               "    db " + ",".join(str(b) for b in definition[4:offset]))
        for obj in layout.objects:
            text = f" {obj.text!r}" if obj.text is not None else ""
            w.emit(f"    ; object {obj.number}: {obj.kind}{text}",
                   "    db " + ",".join(str(b) for b in obj.definition))
        w.emit("    db 0", f"{p}dialog_end:")
        w.emit(f"{p}handlers:",
               f"    db {layout.focus_object},{len(layout.handler_rows)}")
        for number, sub in layout.handler_rows:
            w.emit(f"    db {number}", f"    dw sub_{mangle(sub)}")
        # Binding table (M3b, ARCHITECTURE D3): count, then 9-byte rows of
        # object number, kind (1 TEXTBOX / 2 CHECKBOX / 3 LABEL, M5d),
        # variable address, capacity (TEXTBOX; shown text of a LABEL; 0 for
        # CHECKBOX), record template address and the declaring source line
        # (for runtime error reports).
        if layout.bindings or self.bindings_on:
            w.emit(f"{p}bindings:", f"    db {len(layout.bindings)}")
        for row in layout.bindings:
            kind = {1: "TEXTBOX", 2: "CHECKBOX", 3: "LABEL", 4: "RADIO", 5: "NUMBERBOX",
                    6: "LIST", 7: "CHOICE", 8: "SLIDER"}[row.kind]
            w.emit(
                f"    ; {kind} {row.var_name} (object {row.number}), line {row.line}",
                f"    db {row.number},{row.kind}",
                f"    dw var_{mangle(row.var_name)}",
                f"    db {row.capacity}",
                f"    dw {p}tpl_{row.number}",
                f"    dw {row.line}",
            )
        for row in layout.bindings:
            if row.kind == BIND_NUMBER:
                self._number_descriptor(p, row)
                continue
            if row.kind in (BIND_LIST, BIND_CHOICE, BIND_SLIDER):
                self._phase2_descriptor(p, row)
                continue
            w.emit(f"{p}tpl_{row.number}:", "    db " + ",".join(str(b) for b in row.template))

    def _number_descriptor(self, p: str, row) -> None:
        """A NUMBERBOX descriptor (M6; runtime "Number fields"): the record
        prefix with the runtime legal-character list's address, then MIN,
        MAX, spinner object, shadow index and the invalid-input alert."""
        w, t, widget = self.w, row.template, row.widget
        at = LEGAL_ADDR_OFFSET
        alert = f"{p}numalert_{row.number}"
        text = (f"{widget.caption}: enter a whole number from {widget.low} to {widget.high}"
                if widget.caption else f"Enter a whole number from {widget.low} to {widget.high}")
        self.static_alerts.append((alert, text))
        w.emit(f"{p}tpl_{row.number}:",
               "    db " + ",".join(str(b) for b in t[:at]),
               "    dw rt_num_legal",
               "    db 0",
               "    db " + ",".join(str(b) for b in t[at + 3:]),
               f"    dw {widget.low & 0xFFFF},{widget.high & 0xFFFF}",
               f"    db {row.spinner},{self.shadow_index[id(row)]}",
               f"    dw {alert},{alert}_end-{alert}")

    def _phase2_descriptor(self, p: str, row) -> None:
        """A LIST / CHOICE / SLIDER descriptor (M6 Phase 2; the layouts are
        documented with the runtime's "LIST", "CHOICE" and "SLIDER" parts)."""
        w, t, widget, n = self.w, row.template, row.widget, row.number

        def handler(name):
            return f"sub_{mangle(name)}" if name else "0"

        def db(data):
            return "    db " + ",".join(str(b) for b in data)

        if row.kind == BIND_SLIDER:
            # handle travel: the bar less its two arrow buttons and the handle
            span = SLIDER_BAR[2] - 2 * SCROLL_ARROW - SLIDER_HANDLE
            page = max(1, (widget.high - widget.low) // 10)
            w.emit(f"{p}tpl_{n}:", db(t),
                   f"    dw {widget.low & 0xFFFF},{widget.high & 0xFFFF},{page},{span}",
                   f"    dw {handler(widget.change)}",
                   f"    db {self.slider_index[id(row)]}")
            return
        count = widget.count
        if isinstance(count, ast.IntLiteral):
            count_label = f"{p}lcnt_{n}"
            w.emit(f"{count_label}: dw {count.value}")
        else:
            count_label = f"var_{mangle(count.name)}"
        table = f"{p}ltab_{n}"
        array = f"cgarr_{mangle(widget.items)}"
        if row.kind == BIND_LIST:
            record, bar = t[:LIST_RECORD_LEN], t[LIST_RECORD_LEN:]
            track = int.from_bytes(bar[12:14], "little")
            w.emit(f"{p}tpl_{n}:", db(record[:25]), f"    dw {table}", "    db 0", db(record[28:]),
                   db(bar),
                   f"    dw {count_label},{array},{table}",
                   f"    db {row.capacity},{row.spinner}",
                   f"    dw {track},{handler(widget.change)},{handler(widget.action)}")
        else:
            w.emit(f"{p}tpl_{n}:", db(t[:24]), f"    dw {table}", "    db 0", db(t[27:]),
                   f"    dw {count_label},{array},{table}",
                   f"    db {row.spinner}",
                   f"    dw {handler(widget.change)}")
        # the item pointer table (3 bytes per entry: address, bank). Owner
        # XAnne (M7 retest, issue L1): Rosanne draws every visible row from
        # this table, also rows at or past the count, so it has a slot for
        # each element and each visible row; the word before it says how
        # many, and rt_items_build points the unused ones at "".
        slots = max(widget.length, widget.rows if row.kind == BIND_LIST else 0)
        w.emit(f"    dw {slots}", f"{table}: defs {3 * slots}")

    def _phase1_data(self) -> None:
        """Window table, menus and timer data (M6 Phase 1)."""
        w, program = self.w, self.program
        if self.p1["WINDOWS"]:
            w.emit("gui_windows:", f"    db {len(self.layouts)}")
            for index in range(len(self.layouts)):
                p = "gui_" if index == 0 else f"gui_w{index + 1}_"
                w.emit(f"    dw {p}dialog,{p}handlers,{p}bindings")
        if program.menus:
            data = bytearray()
            items, ticks = [], []
            for title_no, menu in enumerate(program.menus, start=1):
                data += bytes((0x80, 0, 0)) + menu.title.encode("ascii") + b"|"
                # Entry numbers count items only: Rosanne does not number
                # divider lines (owner XAnne, UIPROBE P1: "Tick me", after a
                # divider, was reported as entry 1).
                entry = 0
                for index, item in enumerate(menu.items):
                    last = index == len(menu.items) - 1
                    end = b"\0" if last else b"|"
                    if item.text == "-":
                        data += bytes((0x80,)) + b"_" + end
                        continue
                    status = 0x80 | (0x02 if item.tick else 0)
                    if item.key:
                        key = bytes((ord(item.key.lower()), 0x04))
                    else:
                        key = bytes(2) if self.legacy_menu_hotkeys else NO_HOTKEY
                    data += bytes((status,)) + key + item.text.encode("ascii") + end
                    items.append((title_no, entry, item.handler))
                    if item.tick:
                        ticks.append((title_no, entry, item.tick))
                    entry += 1
            data += b"\0"
            if len(data) > MENU_AREA:  # the Tasks menu is checked at run time
                first = program.menus[0]
                raise SourceError(first.line, first.column,
                                  f"the menus need {len(data)} bytes; Rosanne allows "
                                  f"{MENU_AREA} for the whole menu bar")
            w.emit("    ; menu bar after the Tasks menu (ROSAN283 os_ddm_define format)",
                   "gui_menu_def:", "    db " + ",".join(str(b) for b in data), "gui_menu_def_end:")
            w.emit("gui_menu_items:", f"    db {len(items)}")
            for title_no, entry, handler in items:
                w.emit(f"    db {title_no},{entry}", f"    dw sub_{mangle(handler)}")
            w.emit("gui_menu_ticks:", f"    db {len(ticks)}")
            for title_no, entry, var in ticks:
                w.emit(f"    db {title_no},{entry}", f"    dw var_{mangle(var)}")
        if program.timer is not None:
            # os_set_timer record: +2 timer 0, +3 repeating, +4 1/16 s units
            w.emit("gui_timer_rec:", "    dw 1", "    db 0,1",
                   f"    dw {program.timer.seconds * (1 if program.timer.ticks else 16)}", "    dw 0,0,0",
                   "gui_timer_handler:", f"    dw sub_{mangle(program.timer.handler)}")

    # ------------------------------------------------------------- statements
    def statement(self, item: BodyItem) -> None:
        if isinstance(item, ast.Assign):
            self.w.annotate(item.line)
            self.assign(item)
        elif isinstance(item, ast.AssignIndex):  # M6 Phase 2
            self.w.annotate(item.line)
            self.assign_index(item)
        elif isinstance(item, ast.RecordCopy):  # M10
            self.w.annotate(item.line)
            self.record_copy(item)
        elif isinstance(item, ast.Exit):
            self.w.annotate(item.line)
            # M5c: EXIT SUB returns like END SUB (nothing is on the stack at
            # statement level); EXIT ends the program from any depth.
            self.w.emit("    ret" if item.sub else "    jp rt_exit")
        elif isinstance(item, ast.CallSub):
            self.w.annotate(item.line)
            self.w.emit(f"    call sub_{mangle(item.name)}")  # M5c
        elif isinstance(item, (ast.OpenFile, ast.CloseFile, ast.PrintFile, ast.LineInput,
                               ast.Kill, ast.NameFile)):  # M7 sequential files
            self.w.annotate(item.line)
            self.file_statement(item)
        elif isinstance(item, ast.Randomize):  # M7
            self.w.annotate(item.line)
            self.features.update(("IMATH", "DIV"))
            if item.value is None:
                self.w.emit("    call rt_randomize_r")
            else:
                self.expr(item.value)
                self.w.emit("    call rt_randomize")
        elif isinstance(item, ast.ExitLoop):  # M7: the innermost loop of that kind
            self.w.annotate(item.line)
            label = next(end for kind, end in reversed(self.loops) if kind == item.kind)
            self.w.emit(f"    jp {label}")
        elif isinstance(item, ast.Filesave):
            self.w.annotate(item.line)
            self.filesave(item)
        elif isinstance(item, ast.Fileload):
            self.w.annotate(item.line)
            self.fileload(item)
        elif isinstance(item, ast.Message):
            self.w.annotate(item.line)
            self.message(item)
        elif isinstance(item, ast.Draw):  # M9
            self.w.annotate(item.line)
            self.draw(item)
        elif isinstance(item, ast.TextOp):  # M9 Stage C
            self.w.annotate(item.line)
            self.text_statement(item)
        elif isinstance(item, ast.DbOp):  # M10 Stages B / C
            self.w.annotate(item.line)
            self.db_statement(item)
        elif isinstance(item, ast.BitmapOp):  # M12
            self.w.annotate(item.line)
            self.bitmap_statement(item)
        elif isinstance(item, ast.PageOp):  # M12 printing
            self.w.annotate(item.line)
            self.page_statement(item)
        elif isinstance(item, ast.Beep):  # M6
            self.w.annotate(item.line)
            self.w.emit("    call rt_beep")
        elif isinstance(item, ast.TimerSwitch):  # M6
            self.w.annotate(item.line)
            self.w.emit("    call rt_timer_start" if item.on else "    call rt_timer_stop")
        elif isinstance(item, ast.Show):  # M6: takes effect when the handler returns
            self.w.annotate(item.line)
            index = next(i for i, win in enumerate(self.windows) if win.name == item.name)
            # `ld (hl),n`, not `ld a,n`: asmcheck A4 keeps OS function
            # numbers out of A in generated code
            self.w.emit("    ld hl,rt_win_next", f"    ld (hl),{index + 1}")
        elif isinstance(item, ast.Focus):  # M6: applied by rt_gui_post
            self.w.annotate(item.line)
            self.focus(item)
        elif isinstance(item, IfBlock):
            self.w.annotate(item.line)
            self.if_block(item)
        elif isinstance(item, WhileBlock):
            self.w.annotate(item.line)
            self.while_block(item)
        elif isinstance(item, ForBlock):
            self.w.annotate(item.line)
            self.for_block(item)
        else:
            raise AssertionError(f"unexpected body item: {type(item).__name__}")

    def _file_label(self, name: str) -> str:
        key = name.upper()
        if key not in self.file_names:
            self.file_names[key] = f"pb_file_{len(self.file_names)}"
        return self.file_names[key]

    def filesave(self, node: ast.Filesave) -> None:
        """FILESAVE: build the value in rt_file_buf (guarded), then save it.

        Semantics bounds the value to FILE_TEXT_MAX bytes, so the build
        cannot overflow; rt_put still guards it.
        """
        self._mark_line(node.line)
        self._begin_string("rt_file_buf", FILE_TEXT_MAX + 1)
        self._append_parts(node.value)
        self.w.emit(
            "    xor a",
            "    ld (de),a",
            f"    ld hl,{self._file_label(node.filename.value)}",
            "    call rt_file_save",
        )

    def fileload(self, node: ast.Fileload) -> None:
        """FILELOAD: the runtime replaces the variable only on success."""
        var = self.program.variables[node.value.name]
        self._mark_line(node.line)
        self.w.emit(
            f"    ld hl,{self._file_label(node.filename.value)}",
            f"    ld de,var_{mangle(node.value.name)}",
            f"    ld c,{var.capacity}",
            "    call rt_file_load",
        )

    def file_statement(self, node) -> None:
        """M7 sequential files (LANGUAGE-SPEC §7.1): every outcome lands in
        IOERR (rt_fio_err); nothing here stops the program except the usual
        string and index errors of the expressions."""
        w = self.w
        self.features.add("FIO")
        if isinstance(node, ast.OpenFile):
            mode = 0 if node.mode == "INPUT" else 1
            if isinstance(node.filename, ast.StrLiteral):
                w.emit(f"    ld hl,{self._file_label(node.filename.value)}",
                       f"    ld bc,{mode * 256 + node.channel}", "    call rt_fio_open")
            else:  # M13: a STRING name, checked at run time (IOERR 247: not opened)
                skip = w.new_label("cgfn")
                desc = self._file_desc(node.filename, "rt_dyn_desc", skip)
                w.emit(f"    ld hl,{desc}", f"    ld bc,{mode * 256 + node.channel}",
                       "    call rt_fio_open", f"{skip}:")
        elif isinstance(node, ast.CloseFile):
            if node.channel is None:
                w.emit("    call rt_fio_close_all")
            else:
                w.emit(f"    ld c,{node.channel}", "    call rt_fio_close")
        elif isinstance(node, ast.PrintFile):
            self._mark_line(node.line, node.value)
            value = node.value
            if getattr(value, "typ", "STRING") != "STRING":
                value = ast.Call(value.line, value.column, "STR$", [value])
            self._begin_string("rt_file_buf", FILE_TEXT_MAX + 1)
            self._append_parts(value)
            w.emit("    xor a", "    ld (de),a", f"    ld c,{node.channel}", "    call rt_fio_print")
        elif isinstance(node, ast.LineInput):
            var = self.program.variables[node.name]
            if node.index is not None:
                self._mark_line(node.line)  # the element's index is checked (index error)
                self._elem_addr(node.name, node.index, write=True)
            else:
                self._mark_line(node.line)
                w.emit(f"    ld hl,var_{mangle(node.name)}")
            w.emit(f"    ld b,{var.capacity}", f"    ld c,{node.channel}", "    call rt_fio_input")
            if node.index is not None:  # M8: a failed read leaves the window as it was read
                self._bank_put(node.name)
        elif isinstance(node, ast.Kill):
            skip = w.new_label("cgfn")
            first = self._file_desc(node.filename, "rt_dyn_desc", skip)
            w.emit(f"    ld hl,{first}", "    call rt_fio_kill", f"{skip}:")
        else:
            skip = w.new_label("cgfn")
            first = self._file_desc(node.filename, "rt_dyn_desc", skip)
            second = self._file_desc(node.new_name, "rt_dyn_desc2", skip)
            w.emit(f"    ld hl,{first}", f"    ld de,{second}", "    call rt_fio_name", f"{skip}:")

    def _file_desc(self, expr: ast.Expr, dynamic: str, skip: str) -> str:
        """M9: the descriptor label of a file name: a literal's own, or for a
        STRING expression *dynamic*, filled by rt_fname at run time (an
        invalid name sets IOERR 247 and jumps to *skip*)."""
        if isinstance(expr, ast.StrLiteral):
            return self._file_label(expr.value)
        self.features.update(("FNAME", "FIO"))
        buf = self._string_ptr(expr)
        self.w.emit(f"    ld de,{dynamic}", "    call rt_fname", f"    jp c,{skip}")
        if buf is not None:
            self._scratch_release(buf)
        return dynamic

    def text_statement(self, node: ast.TextOp) -> None:
        """M9 TEXT op Buffer, ...: arguments first (they may use TEXT
        functions, which share the runtime cells), then the cells, then the
        routine with HL = the buffer record."""
        w = self.w
        self.features.add("TEXT")
        record = f"var_{mangle(node.name)}"
        w.emit(f"    ld hl,{node.line}", "    ld (rt_err_line),hl")
        if node.op in ("LOAD", "SAVE"):
            self.features.add("FIO")
            skip = w.new_label("cgfn")
            desc = self._file_desc(node.values[0], "rt_dyn_desc", skip)
            w.emit(f"    ld hl,{desc}", "    ld (rt_file_desc),hl", f"    ld hl,{record}",
                   f"    call rt_text_{node.op.lower()}", f"{skip}:")
            return
        if node.op in ("REMOVE", "COPY", "PASTE"):  # M10 (runtime PB_TXRANGE)
            self.features.add("TXRANGE")
            values = list(node.values)
            other = values.pop(0 if node.op == "COPY" else 2) if node.op != "REMOVE" else None
            cells = {"REMOVE": ("rt_tx_n", "rt_tx_c", "rt_tx_n2", "rt_tx_c2"),
                     "COPY": ("rt_tx_n", "rt_tx_c", "rt_tx_n2", "rt_tx_c2")[:len(values)],
                     "PASTE": ("rt_tx_n", "rt_tx_c")}[node.op]
            self._text_args(values)
            for cell in reversed(cells):
                w.emit("    pop hl", f"    ld ({cell}),hl")
            if other is not None:
                w.emit(f"    ld hl,var_{mangle(other.name)}", "    ld (rt_tx_src),hl")
            if node.op == "COPY":
                w.emit(f"    ld a,{0 if values else 1}", "    ld (rt_tx_all),a")
            w.emit(f"    ld hl,{record}", f"    call rt_text_{node.op.lower()}")
            return
        cells = {"INSERT": ("rt_tx_n", "rt_tx_c", "rt_tx_str"), "DELETE": ("rt_tx_n", "rt_tx_c", "rt_tx_k"),
                 "SPLIT": ("rt_tx_n", "rt_tx_c"), "JOIN": ("rt_tx_n",), "CLEAR": ()}[node.op]
        held = self._text_args(node.values)
        for cell in reversed(cells):
            w.emit("    pop hl", f"    ld ({cell}),hl")
        w.emit(f"    ld hl,{record}", f"    call rt_text_{node.op.lower()}")
        for buf in held:
            self._scratch_release(buf)

    def _db_table(self, name: str) -> str:
        """M10: the database table of record array *name* (data section)."""
        self.features.update(("DB", "BANK", "ARRAYS", "FIO", "RECORDS"))
        self.db_arrays.add(name)
        return f"cgdb_{mangle(name)}"

    def _bitmap_record(self, name: str) -> None:
        """HL = the record of BITMAP *name*: its label, or (M13) for a BITMAP
        parameter the address the parameter holds."""
        if self.program.variables[name].type == "BITMAPREF":
            self.w.emit(f"    ld hl,(var_{mangle(name)})")
        else:
            self.w.emit(f"    ld hl,var_{mangle(name)}")

    def _bitmap_size_args(self, name: str) -> None:
        """rt_dw_args+4, +6 = the bitmap's current width and height."""
        self._bitmap_record(name)
        self.w.emit("    ld de,4", "    add hl,de", "    ld de,rt_dw_args+4", "    ld bc,4", "    ldir")

    def bitmap_statement(self, node: ast.BitmapOp) -> None:
        """M12 BITMAP op Name, ...: arguments into the runtime's cells, then
        the routine with HL = the bitmap record (runtime "bitmaps")."""
        w = self.w
        # M14 (D2): the bitmap routines are assembled with the BITMAP part (and the
        # bank part it uses). A statement on a BITMAP parameter needs them even in
        # a program that declares no BITMAP of its own (lib/sprite.pbas,
        # lib/toolbar.pbas included and unused): without this, Pasmo stopped with
        # "Symbol 'rt_bmp_put' is undefined". A program with a BITMAP variable
        # already sets them (with ARRAYS, which the bank part uses), so its bytes
        # do not change.
        self.features.update(("BITMAP", "BANK", "ARRAYS"))
        w.emit(f"    ld hl,{node.line}", "    ld (rt_err_line),hl")
        if node.op == "MASK" or (node.op == "PUT" and len(node.values) == 6):  # M13: a part, a mask
            self.features.add("BMPPART")
            # values: x, y [, sx, sy, w, h] into +0 x, +2 y, +8 sx, +10 sy, +4 w, +6 h
            for value, offset in zip(node.values, (0, 2, 8, 10, 4, 6)):
                self.expr(value)
                w.emit(f"    ld (rt_dw_args+{offset}),hl")
            if len(node.values) == 2:  # MASK of the whole image
                w.emit("    ld hl,0", "    ld (rt_dw_args+8),hl", "    ld (rt_dw_args+10),hl")
                self._bitmap_size_args(node.name)
            if node.op == "MASK":
                self._bitmap_record(node.mask)
                w.emit("    ld (rt_bmp_mrec),hl")
                self._bitmap_record(node.name)
                w.emit("    call rt_bmp_mask")
            else:
                self._bitmap_record(node.name)
                w.emit("    call rt_bmp_part")
            return
        if node.op in ("GET", "PUT"):
            for i, value in enumerate(node.values):
                self.expr(value)
                w.emit(f"    ld (rt_dw_args+{2 * i}),hl")
            if node.op == "GET" and len(node.values) == 2:
                if self.program.variables[node.name].type == "BITMAPREF":  # M13
                    self._bitmap_size_args(node.name)
                else:  # as M12 (accepted executables keep their bytes)
                    record = f"var_{mangle(node.name)}"
                    w.emit(f"    ld hl,({record}+4)", "    ld (rt_dw_args+4),hl",
                           f"    ld hl,({record}+6)", "    ld (rt_dw_args+6),hl")
            self._bitmap_record(node.name)
            w.emit(f"    call rt_bmp_{node.op.lower()}")
            return
        # SAVE / LOAD: the database part's safe-save steps (runtime "databases")
        self.features.update(("DB", "BANK", "ARRAYS", "FIO", "RECORDS", "BMPFILE"))
        self.uses_fsafe = self.uses_fsafe or node.op == "SAVE"
        skip = w.new_label("cgfn")
        desc = self._file_desc(node.values[0], "rt_dyn_desc", skip)
        w.emit(f"    ld hl,{desc}", "    ld (rt_file_desc),hl")
        self._bitmap_record(node.name)
        w.emit(f"    call rt_bmp_{node.op.lower()}", f"{skip}:")

    def page_statement(self, node: ast.PageOp) -> None:
        """M12 PAGE op: the numbers into rt_pg_args (words), TEXT's string in
        HL, then the routine (runtime "printing"); IOERR is the outcome."""
        w = self.w
        self.features.update(("PAGE", "FIO"))
        w.emit(f"    ld hl,{node.line}", "    ld (rt_err_line),hl")
        numbers = node.values[:2] if node.op == "TEXT" else node.values
        for i, value in enumerate(numbers):
            self.expr(value)
            w.emit(f"    ld (rt_pg_args+{2 * i}),hl")
        if node.op == "FONT":
            w.emit(f"    ld hl,{1 if node.bold else 0}", "    ld (rt_pg_args+2),hl")
        if node.op == "LINE" and len(node.values) == 4:
            w.emit("    ld hl,1", "    ld (rt_pg_args+8),hl")  # one point thick
        buf = None
        if node.op == "TEXT":
            buf = self._string_ptr(node.values[2])
        w.emit(f"    call rt_pg_{node.op.lower()}")
        if buf is not None:
            self._scratch_release(buf)

    def db_statement(self, node: ast.DbOp) -> None:
        """M10 DB op Array, ...: arguments into the runtime's cells, then the
        routine with HL = the database table (runtime "databases")."""
        w = self.w
        table = self._db_table(node.name)
        w.emit(f"    ld hl,{node.line}", "    ld (rt_err_line),hl")
        values = node.values
        self.uses_fsafe = self.uses_fsafe or node.op in ("LOAD", "SAVE")
        if node.op == "LOAD":
            skip = w.new_label("cgfn")
            desc = self._file_desc(values[1], "rt_dyn_desc", skip)
            w.emit(f"    ld hl,{desc}", "    ld (rt_file_desc),hl", f"    ld hl,{table}",
                   "    call rt_db_load", f"    ld (var_{mangle(values[0].name)}),hl", f"{skip}:")
            return
        if node.op == "SAVE":
            skip = w.new_label("cgfn")
            self.expr(values[0])
            w.emit("    ld (rt_db_n),hl")
            desc = self._file_desc(values[1], "rt_dyn_desc", skip)
            w.emit(f"    ld hl,{desc}", "    ld (rt_file_desc),hl", f"    ld hl,{table}",
                   "    call rt_db_save", f"{skip}:")
            return
        if node.op in ("NEW", "DELETE"):
            count = f"var_{mangle(values[0].name)}"
            if node.op == "DELETE":
                self.expr(values[1])
                w.emit("    ld (rt_db_k),hl")
            w.emit(f"    ld hl,({count})", "    ld (rt_db_n),hl", f"    ld hl,{table}",
                   f"    call rt_db_{node.op.lower()}", f"    ld ({count}),hl")
            return
        self.db_sort_search(node, table)

    def db_sort_search(self, node: ast.DbOp, table: str) -> None:
        """M10 Stage C: DB SORT / DB SEARCH Array, Count, Index[, Found], field
        (LANGUAGE-SPEC §5.10): the count, the index's descriptor and the
        field's offset, size and kind into the runtime's cells; SEARCH's text
        is copied first (rt_db_pattern), so it may use any STRING expression."""
        w = self.w
        values = node.values
        field = self.program.variables[f"{node.name}%{node.key}"]
        kind = {"INTEGER": 0, "STRING": 1, "REAL": 2}[field.type]
        flags = (kind | (0x10 if "DESC" in node.flags else 0) | (0x20 if "NOCASE" in node.flags else 0)
                 | (0x40 if "KEEP" in node.flags else 0))
        size = field.capacity if field.type == "STRING" else 5 if field.type == "REAL" else 2
        w.emit(f"    ld a,{flags}", "    ld (rt_db_fk),a")
        if node.op == "SEARCH":
            buf = self._string_ptr(values[3])
            w.emit("    call rt_db_pattern")
            if buf is not None:
                self._scratch_release(buf)
        self.expr(values[0])
        w.emit("    ld (rt_db_n),hl", f"    ld hl,cgarr_{mangle(values[1].name)}", "    ld (rt_db_ord),hl",
               f"    ld hl,{field.alias[1]}", "    ld (rt_db_foff),hl", f"    ld hl,{size}",
               "    ld (rt_db_flen),hl", f"    ld hl,{table}", f"    call rt_db_{node.op.lower()}")
        if node.op == "SEARCH":
            w.emit(f"    ld (var_{mangle(values[2].name)}),hl")

    def _text_args(self, values) -> list:
        """Push each argument (an INTEGER's value, a STRING's address); the
        scratch buffers holding built strings are returned, still held."""
        held = []
        for value in values:
            if getattr(value, "typ", None) == "STRING":
                buf = self._string_ptr(value)
                if buf is not None:
                    held.append(buf)
            else:
                self.expr(value)
            self.w.emit("    push hl")
        return held

    def focus(self, node: ast.Focus) -> None:
        for index, layout in enumerate(self.layouts):
            for row in layout.bindings:
                if row.var_name == node.name and row.kind in (1, 2, BIND_NUMBER):
                    self.w.emit("    ld hl,rt_focus_obj", f"    ld (hl),{row.number}")
                    if self.p1["WINDOWS"]:
                        self.w.emit("    ld hl,rt_focus_win", f"    ld (hl),{index + 1}")
                    return
        raise AssertionError(f"FOCUS {node.name}: no bound control (semantics checks this)")

    def ask(self, node: ast.Assign) -> None:
        """M6: `v = ASK(text, captions...)`: text built in rt_alert_buf
        (guarded, at most ASK_TEXT_MAX bytes), then rt_ask adds the button
        block and returns the button number 1..n in HL."""
        text, captions = node.value.args[0], [a.value for a in node.value.args[1:]]
        label = self.w.new_label("ask")
        self.asks.append((label, captions))
        self._mark_line(node.line)
        self._begin_string("rt_alert_buf", ASK_TEXT_MAX + 1)
        self._append_parts(text)
        self.w.emit(f"    ld hl,{label}", f"    ld bc,{label}_end-{label}",
                    "    call rt_ask", f"    ld (var_{mangle(node.name)}),hl")

    def _elem_addr(self, name: str, index: ast.Expr, write: bool = False) -> None:
        """HL = address of element *index* of array *name*; rt_index checks
        1 <= index <= length ("index out of range" at rt_err_line).

        M8: for a BANKED array HL is a near window instead: a copy of the
        element to read (rt_bank_get), or, with *write*, the write window
        holding the element, which _bank_put stores back."""
        self.features.add("ARRAYS")
        self.expr(index)
        var = self.program.variables[name]
        if getattr(var, "banked", False):
            routine = "rt_bank_wref" if write else "rt_bank_get"
            alias = getattr(var, "alias", None)
            if alias is not None:  # M10: the record's element, then the field in it
                self.w.emit(f"    ld de,cgbank_{mangle(alias[0])}", f"    call {routine}")
                if alias[1]:
                    self.w.emit(f"    ld de,{alias[1]}", "    add hl,de")
                return
            self.w.emit(f"    ld de,cgbank_{mangle(name)}", f"    call {routine}")
            return
        self.w.emit(f"    ld de,cgarr_{mangle(name)}", "    call rt_index")

    def record_copy(self, node: ast.RecordCopy) -> None:
        """M10: `A = B` between records of one TYPE (or a clear, for a LOCAL
        record). The source is located first (a resident record in place, a
        BANKED one in a read window), then the target (a BANKED one through
        the write window, stored back by rt_bank_put); one ldir moves the
        record's bytes."""
        w = self.w
        self.features.add("RECORDS")
        self._mark_line(node.line)
        if node.src is None:  # a cleared record: one zero byte, then an overlapping ldir
            if node.index is None:
                w.emit(f"    ld hl,var_{mangle(node.name)}")
            else:
                self._elem_addr(node.name, node.index, write=True)
            self._record_dst_end(node.size)
            w.emit("    ld (hl),0")
            if node.size > 1:
                w.emit("    ld d,h", "    ld e,l", "    inc de", f"    ld bc,{node.size - 1}", "    ldir")
            if node.index is not None:
                self._bank_put(node.name)
            return
        if node.src_index is None:
            w.emit(f"    ld hl,var_{mangle(node.src)}")
        else:
            self._elem_addr(node.src, node.src_index)
        w.emit("    push hl")
        if node.index is None:
            w.emit(f"    ld hl,var_{mangle(node.name)}")
        else:
            self._elem_addr(node.name, node.index, write=True)
        self._record_dst_end(node.size)
        w.emit("    ex de,hl", "    pop hl", f"    ld bc,{node.size}", "    ldir")
        if node.index is not None:
            self._bank_put(node.name)

    def _record_dst_end(self, size: int) -> None:
        """rt_dst_end = the last byte of the record at HL (the active
        destination of the bytes about to be written; HL kept)."""
        self.w.emit("    push hl", f"    ld bc,{size - 1}", "    add hl,bc",
                    "    ld (rt_dst_end),hl", "    pop hl")

    def _bank_put(self, name: str) -> None:
        """M8: after a write through _elem_addr(write=True)."""
        if getattr(self.program.variables[name], "banked", False):
            self.w.emit("    call rt_bank_put")

    def assign_index(self, node: ast.AssignIndex) -> None:
        """Name(index) = value: the value is built first (a STRING in a
        scratch buffer), then the element is located and written; a STRING
        is copied under rt_put with the element's own capacity."""
        w = self.w
        var = self.program.variables[node.name]
        self._mark_line(node.line)
        if var.type == "REAL":  # M7: value first, then the element (its index may use FA)
            self.real(node.value)
            w.emit("    call rt_fpush")
            self._elem_addr(node.name, node.index, write=True)
            w.emit("    ex de,hl", "    call rt_fpopa", "    ex de,hl", "    call rt_fst")
            self._bank_put(node.name)
            return
        if var.type != "STRING":
            self.expr(node.value)
            w.emit("    push hl")
            self._elem_addr(node.name, node.index, write=True)
            w.emit("    pop de", "    ld (hl),e", "    inc hl", "    ld (hl),d")
            self._bank_put(node.name)
            return
        buf = self._scratch_acquire(node)
        self._begin_string(buf, SCRATCH_STRING_MAX + 1)
        self._append_parts(node.value)
        w.emit("    xor a", "    ld (de),a")
        self._elem_addr(node.name, node.index, write=True)
        w.emit("    ld d,h", "    ld e,l", f"    ld bc,{var.capacity - 1}", "    add hl,bc",
               "    ld (rt_dst_end),hl", f"    ld hl,{buf}", f"    ld bc,{SCRATCH_STRING_MAX + 1}",
               "    call rt_str_copy", "    xor a", "    ld (de),a")
        self._field_zfill(var)
        self._bank_put(node.name)
        self._scratch_release(buf)

    def _field_zfill(self, var) -> None:
        """M10: after a STRING written into a record field (DE = its NUL),
        the bytes up to the field's end become zero, so a record's bytes
        depend only on its values (records and database files, §5.8)."""
        if getattr(var, "alias", None) is not None:
            self.features.add("RECORDS")
            self.w.emit("    call rt_rec_zfill")

    def assign(self, node: ast.Assign) -> None:
        if isinstance(node.value, ast.Call) and node.value.name == "ASK":
            self.ask(node)
            return
        var = self.program.variables[node.name]
        if var.type == "BITMAPREF":  # M13: a BITMAP argument: its record's address
            self._bitmap_record(node.value.name)
            self.w.emit(f"    ld (var_{mangle(node.name)}),hl")
            return
        if var.type == "STRING":
            self._assign_string(node, var.capacity)
            self._field_zfill(var)
            return
        if var.type == "REAL":  # M7
            self._mark_line(node.line)
            self.real(node.value)
            self.w.emit(f"    ld hl,var_{mangle(node.name)}", "    call rt_fst")
            return
        self._mark_line(node.line, node.value)
        self.expr(node.value)
        self.w.emit(f"    ld (var_{mangle(node.name)}),hl")

    def _assign_string(self, node: ast.Assign, capacity: int) -> None:
        """STRING assignment (M5a: any STRING expression).

        The value is built directly in the variable unless the variable is
        read by a part after the first one (``S$ = "x" + S$``): writing the
        first part would destroy what a later part reads, so the value is
        built in a scratch buffer and then copied. Reading the destination in
        the first part is safe: a whole-variable or substring copy of itself
        moves bytes to the same or earlier positions, and computed sources /
        integer arguments are evaluated before anything is written. Semantics
        rejects values that cannot fit; whatever might not fit is caught by
        rt_put, before anything is written past the variable.
        """
        dest = f"var_{mangle(node.name)}"
        self._mark_line(node.line)
        parts = _concat_parts(node.value)
        if not any(_reads_var(part, node.name) for part in parts[1:]):
            self._begin_string(dest, capacity)
            self._append_parts(node.value)
            self.w.emit("    xor a", "    ld (de),a")
            return
        buf = self._scratch_acquire(node)
        self._begin_string(buf, SCRATCH_STRING_MAX + 1)
        self._append_parts(node.value)
        self.w.emit("    xor a", "    ld (de),a")
        self._begin_string(dest, capacity)
        self.w.emit(f"    ld hl,{buf}", f"    ld bc,{SCRATCH_STRING_MAX + 1}",
                    "    call rt_str_copy", "    xor a", "    ld (de),a")
        self._scratch_release(buf)

    # ------------------------------------------------------- scratch pool (M5a)
    def _scratch_acquire(self, node, prefer: str | None = None) -> str:
        """Take a free scratch buffer (LIFO by nesting); *prefer* keeps the
        M2 choice (LEN used the second buffer) where it is free."""
        if prefer is not None and prefer not in self.scratch_held:
            buf = prefer
        else:
            free = [b for b in SCRATCH_POOL if b not in self.scratch_held]
            if not free:
                raise SourceError(
                    node.line,
                    node.column,
                    f"string expression is nested too deeply: it needs more than "
                    f"{len(SCRATCH_POOL)} temporary strings at once; split it "
                    "into simpler statements",
                )
            buf = free[0]
        self.scratch_held.append(buf)
        self.scratch_extra = max(self.scratch_extra, SCRATCH_POOL.index(buf) - 1)
        return buf

    def _scratch_release(self, buf: str) -> None:
        self.scratch_held.remove(buf)

    def _mark_line(self, line: int, *exprs: ast.Expr) -> None:
        """Record *line* in rt_err_line when the statement may build a string.

        With no *exprs* the statement always builds one (STRING assignment,
        dynamic MESSAGE); otherwise only if an expression calls a string
        function (directly, or inside LEN).
        """
        if exprs and not any(
            _builds_string(e) or self._has_concat(e) or _may_fail(e) for e in exprs
        ):
            return
        self.w.emit(f"    ld hl,{line}", "    ld (rt_err_line),hl")

    def _has_concat(self, e: ast.Expr) -> bool:
        """True if *e* contains a STRING concatenation (M5a), which builds a
        computed operand in scratch storage."""
        if isinstance(e, ast.Binary):
            if e.op == "+" and self._is_string_expr(e.left):
                return True
            return self._has_concat(e.left) or self._has_concat(e.right)
        if isinstance(e, ast.Call):
            return any(self._has_concat(a) for a in e.args)
        if isinstance(e, ast.Index):
            return self._has_concat(e.index)
        if isinstance(e, ast.Unary):
            return self._has_concat(e.operand)
        return False

    def _begin_string(self, dest: str, capacity: int) -> None:
        """Open a string build: rt_dst_end = last byte of *dest*, DE = *dest*."""
        self.w.emit(
            f"    ld hl,{dest}+{capacity - 1}",
            "    ld (rt_dst_end),hl",
            f"    ld de,{dest}",
        )

    def if_block(self, block: IfBlock) -> None:
        w = self.w
        else_label = w.new_label("cgelse")
        end_label = w.new_label("cgendif")
        self._mark_line(block.line, block.condition)
        self.expr(block.condition)
        w.emit("    ld a,h", "    or l", f"    jp z,{else_label}")
        for item in block.then_body:
            self.statement(item)
        if block.else_body:
            w.emit(f"    jp {end_label}", f"{else_label}:")
            for item in block.else_body:
                self.statement(item)
            w.emit(f"{end_label}:")
        else:
            w.emit(f"{else_label}:")

    def while_block(self, block: WhileBlock) -> None:
        w = self.w
        top = w.new_label("cgwhiletop")
        end = w.new_label("cgwhileend")
        w.emit(f"{top}:")
        self._mark_line(block.line, block.condition)
        self.expr(block.condition)
        w.emit("    ld a,h", "    or l", f"    jp z,{end}")
        self.loops.append(("WHILE", end))
        for item in block.body:
            self.statement(item)
        self.loops.pop()
        w.emit(f"    jp {top}", f"{end}:")

    def for_block(self, block: ForBlock) -> None:
        """Inclusive signed loop, literal STEP +/-1; TO bound evaluated once.

        Equality is checked before the increment so a limit of +32767 / -32768
        does not wrap (POC for_begin/for_end, XAnne-proven).
        """
        w = self.w
        name = block.name
        limit = w.new_label("cgforlimit")
        top = w.new_label("cgfortop")
        end = w.new_label("cgforend")
        step = constant_step(block.step)
        if step not in (1, -1):
            self._for_stepped(block, step)
            return
        descending = step == -1
        self.loop_limits.append(limit)
        self._mark_line(block.line, block.start, block.finish)
        self.expr(block.start)
        w.emit(f"    ld (var_{mangle(name)}),hl")
        self.expr(block.finish)
        w.emit(
            f"    ld ({limit}),hl",
            f"{top}:",
            f"    ld de,(var_{mangle(name)})",
            f"    ld hl,({limit})",
            "    call rt_compare_signed",
            f"    cp {0 if descending else 2}",
            f"    jp z,{end}",
        )
        self.loops.append(("FOR", end))
        for item in block.body:
            self.statement(item)
        self.loops.pop()
        w.emit(
            f"    ld de,(var_{mangle(name)})",
            f"    ld hl,({limit})",
            "    call rt_compare_signed",
            "    cp 1",
            f"    jp z,{end}",
            f"    ld hl,(var_{mangle(name)})",
            "    dec hl" if descending else "    inc hl",
            f"    ld (var_{mangle(name)}),hl",
            f"    jp {top}",
            f"{end}:",
        )

    def _for_stepped(self, block: ForBlock, step: int) -> None:
        """M7: FOR with a constant STEP other than +/-1. The loop ends when the
        distance left to the limit (an exact unsigned 16-bit difference, the
        counter being on the right side of the limit) is smaller than the
        step, so the counter never wraps past +32767 / -32768."""
        w, var = self.w, f"var_{mangle(block.name)}"
        limit = w.new_label("cgforlimit")
        top = w.new_label("cgfortop")
        end = w.new_label("cgforend")
        self.loop_limits.append(limit)
        self._mark_line(block.line, block.start, block.finish)
        self.expr(block.start)
        w.emit(f"    ld ({var}),hl")
        self.expr(block.finish)
        w.emit(f"    ld ({limit}),hl", f"{top}:", f"    ld de,({var})", f"    ld hl,({limit})",
               "    call rt_compare_signed", f"    cp {2 if step > 0 else 0}", f"    jp z,{end}")
        self.loops.append(("FOR", end))
        for item in block.body:
            self.statement(item)
        self.loops.pop()
        if step > 0:
            w.emit(f"    ld hl,({limit})", f"    ld de,({var})")
        else:
            w.emit(f"    ld hl,({var})", f"    ld de,({limit})")
        w.emit("    or a", "    sbc hl,de", f"    ld de,{abs(step)}", "    or a", "    sbc hl,de",
               f"    jp c,{end}", f"    ld hl,({var})", f"    ld de,{step & 0xFFFF}", "    add hl,de",
               f"    ld ({var}),hl", f"    jp {top}", f"{end}:")

    def message(self, node: ast.Message) -> None:
        w = self.w
        value = node.value
        if isinstance(value, ast.StrLiteral):
            label = w.new_label("msgdef")
            self.static_messages.append((label, value.value))
            w.emit(
                f"    ld hl,{label}",
                f"    ld de,{label}_end-{label}",
                "    call rt_alert",
            )
            return
        # Dynamic MESSAGE: build the text in rt_alert_buf (guarded), then
        # rt_alert_dynamic adds the os_alert definition tail and shows it.
        self._mark_line(node.line)
        self._begin_string("rt_alert_buf", ALERT_BUFFER_SIZE + 1)
        self._append_parts(value)
        w.emit("    call rt_alert_dynamic")

    # ------------------------------------------------------------- expressions
    def expr(self, e: ast.Expr) -> None:
        """Emit an INTEGER/BOOLEAN expression; the result lands in HL."""
        w = self.w
        if isinstance(e, ast.IntLiteral):
            w.emit(f"    ld hl,{e.value}")
        elif isinstance(e, ast.BoolLiteral):
            w.emit("    ld hl,1" if e.value else "    ld hl,0")
        elif isinstance(e, ast.Var):
            w.emit(f"    ld hl,(var_{mangle(e.name)})")
        elif isinstance(e, ast.Index):  # M6 Phase 2: INTEGER/BOOLEAN element
            self._elem_addr(e.name, e.index)
            w.emit("    ld e,(hl)", "    inc hl", "    ld d,(hl)", "    ex de,hl")
        elif isinstance(e, ast.Call):
            self.call(e)
        elif isinstance(e, ast.Unary) and e.op == "NOT" and getattr(e, "typ", None) == "INTEGER":
            self.expr(e.operand)  # M7: bitwise complement
            w.emit("    ld a,h", "    cpl", "    ld h,a", "    ld a,l", "    cpl", "    ld l,a")
        elif isinstance(e, ast.Unary) and e.op == "NOT":
            # M5c: HL = 1 if the operand is 0, else 0.
            done = w.new_label("cgnot")
            self.expr(e.operand)
            w.emit("    ld a,h", "    or l", "    ld hl,0", f"    jp nz,{done}",
                   "    inc l", f"{done}:")
        elif isinstance(e, ast.Unary):
            self.expr(e.operand)
            if e.op == "-":
                w.emit("    xor a", "    ld de,0", "    ex de,hl", "    sbc hl,de")
        elif isinstance(e, ast.Binary):
            self.binary(e)
        else:
            raise SourceError(
                e.line, e.column, f"expression node {type(e).__name__} is not supported"
            )

    def binary(self, e: ast.Binary) -> None:
        op = e.op
        if op in ("AND", "OR") and getattr(e, "typ", "BOOLEAN") == "BOOLEAN":
            self._logical(e)
            return
        if op in _WANTED and self._is_string_expr(e.left):
            self._string_compare(e)
            return
        if op in _WANTED and "REAL" in (getattr(e.left, "typ", None), getattr(e.right, "typ", None)):
            self._real_operands(e)  # M7: FB = left, FA = right
            self.w.emit("    call rt_fcmp")
            self._compare_flag_tail(op)
            return
        w = self.w
        self.expr(e.left)
        w.emit("    push hl")
        self.expr(e.right)
        w.emit("    pop de")  # DE=left; HL=right
        if op == "+":
            w.emit("    add hl,de")
        elif op == "-":
            w.emit("    ex de,hl", "    or a", "    sbc hl,de")
        elif op == "*":
            w.emit("    call rt_mul16")
        elif op in ("/", "MOD"):  # M5b: DE = dividend, HL = divisor
            self.features.add("DIV")
            w.emit("    call rt_div16" if op == "/" else "    call rt_mod16")
        elif op in ("AND", "OR", "XOR"):  # M7: bitwise (INTEGER), or BOOLEAN XOR on 0/1
            ins = {"AND": "and", "OR": "or", "XOR": "xor"}[op]
            w.emit("    ld a,h", f"    {ins} d", "    ld h,a", "    ld a,l", f"    {ins} e", "    ld l,a")
        elif op in _WANTED:
            self._compare_tail(op)
        else:
            raise SourceError(e.line, e.column, f"internal: operator {op} has no code generation")

    def _logical(self, e: ast.Binary) -> None:
        """M5c AND / OR, left to right with short-circuit (LANGUAGE-SPEC
        section 3): the right operand runs only if the left one does not
        decide the result. HL = 0 or 1. Nothing is on the stack at either
        jump, and each operand releases its own scratch buffers, so skipping
        the right operand leaves no state behind."""
        w = self.w
        decided = w.new_label("cgand" if e.op == "AND" else "cgor")
        done = w.new_label("cglogic")
        self.expr(e.left)
        w.emit("    ld a,h", "    or l", f"    jp {'z' if e.op == 'AND' else 'nz'},{decided}")
        self.expr(e.right)
        w.emit("    ld a,h", "    or l", f"    jp {'z' if e.op == 'AND' else 'nz'},{decided}",
               f"    ld hl,{1 if e.op == 'AND' else 0}", f"    jp {done}",
               f"{decided}:", f"    ld hl,{0 if e.op == 'AND' else 1}", f"{done}:")

    def _compare_flag_tail(self, op: str) -> None:
        """A holds 0/1/2 (left <, =, > right); leave 0/1 in HL."""
        w = self.w
        yes = w.new_label("cgcmptrue")
        done = w.new_label("cgcmpdone")
        for value in _WANTED[op]:
            w.emit(f"    cp {value}", f"    jp z,{yes}")
        w.emit("    ld hl,0", f"    jp {done}", f"{yes}:", "    ld hl,1", f"{done}:")

    # ------------------------------------------------------------- M7 REAL
    def real(self, e: ast.Expr) -> None:
        """Emit a numeric expression so that its REAL value lands in FA
        (rt_fa). An INTEGER part is evaluated as before and widened exactly
        (rt_fint)."""
        w = self.w
        self.features.add("REAL")
        if getattr(e, "typ", None) == "INTEGER" or isinstance(e, ast.IntLiteral):
            self.expr(e)
            w.emit("    call rt_fint")
        elif isinstance(e, ast.RealLiteral):
            w.emit(f"    ld hl,{self._real_const(e)}", "    call rt_fld")
        elif isinstance(e, ast.Var):
            w.emit(f"    ld hl,var_{mangle(e.name)}", "    call rt_fld")
        elif isinstance(e, ast.Index):
            self._elem_addr(e.name, e.index)
            w.emit("    call rt_fld")
        elif isinstance(e, ast.Unary):
            self.real(e.operand)
            if e.op == "-":
                w.emit("    call rt_fneg")
        elif isinstance(e, ast.Binary):
            self._real_operands(e)
            w.emit(f"    call {_REAL_OPS[e.op]}")
        elif isinstance(e, ast.Call) and e.name in ("MIN", "MAX"):
            self._real_operands(e, *e.args)
            w.emit(f"    call rt_f{e.name.lower()}")
        elif isinstance(e, ast.Call) and e.name == "REALVAL":
            buf = self._string_ptr(e.args[0])
            w.emit("    call rt_fval")
            if buf is not None:
                self._scratch_release(buf)
        elif isinstance(e, ast.Call) and e.name in _REAL_CALLS:
            self.real(e.args[0])
            if _REAL_CALLS[e.name]:
                w.emit(f"    call {_REAL_CALLS[e.name]}")
        else:
            raise AssertionError(f"not a REAL expression: {e}")

    def _real_operands(self, e, left=None, right=None) -> None:
        """FB = left operand, FA = right operand."""
        left = e.left if left is None else left
        right = e.right if right is None else right
        self.real(left)
        self.w.emit("    call rt_fpush")
        self.real(right)
        self.w.emit("    call rt_fpopb")

    def _real_const(self, e: ast.RealLiteral) -> str:
        from fractions import Fraction
        from .real import pack
        data = pack(Fraction(getattr(e, "text", None) or e.value))
        if data not in self.real_consts:
            self.real_consts[data] = f"cgreal_{len(self.real_consts)}"
        return self.real_consts[data]

    def _compare_tail(self, op: str) -> None:
        """A holds rt_compare_signed's 0/1/2; leave 0/1 in HL (POC expr tail)."""
        w = self.w
        yes = w.new_label("cgcmptrue")
        done = w.new_label("cgcmpdone")
        w.emit("    call rt_compare_signed")
        for value in _WANTED[op]:
            w.emit(f"    cp {value}", f"    jp z,{yes}")
        w.emit("    ld hl,0", f"    jp {done}", f"{yes}:", "    ld hl,1", f"{done}:")

    def _string_compare(self, e: ast.Binary) -> None:
        """STRING =/==/<>: point at each operand, then rt_str_compare.

        Literal and variable operands are compared in place (no copy, so no
        length limit). Computed operands (STR$, substrings) are built in
        their own scratch buffer; semantics bounds them by SCRATCH_STRING_MAX.
        """
        w = self.w
        left = self._scratch_acquire(e)
        self._string_operand(e.left, left)
        w.emit("    push hl")
        right = self._scratch_acquire(e)
        self._string_operand(e.right, right)
        w.emit("    ex de,hl", "    pop hl")  # HL = left, DE = right
        self._scratch_release(right)
        self._scratch_release(left)
        yes = w.new_label("cgcmptrue")
        done = w.new_label("cgcmpdone")
        w.emit("    call rt_str_compare")
        for value in _WANTED[e.op]:
            w.emit(f"    cp {value}", f"    jp z,{yes}")
        w.emit("    ld hl,0", f"    jp {done}", f"{yes}:", "    ld hl,1", f"{done}:")

    def call(self, e: ast.Call) -> None:
        w = self.w
        if e.name == "LEN":
            arg = e.args[0]
            if isinstance(arg, ast.StrLiteral):
                w.emit(f"    ld hl,{len(arg.value.encode('utf-8'))}")
            elif isinstance(arg, ast.Var):
                w.emit(
                    f"    ld hl,var_{mangle(arg.name)}",
                    "    call rt_str_len",
                    "    ld h,b",
                    "    ld l,c",
                )
            else:
                # Computed string: build it in a scratch buffer (the second
                # one where free, as in M2), then measure it.
                buf = self._scratch_acquire(arg, prefer=SCRATCH_BUFFERS[1])
                self._string_operand(arg, buf)
                self._scratch_release(buf)
                w.emit("    call rt_str_len", "    ld h,b", "    ld l,c")
            return
        if e.name == "TEXTWIDTH":  # M11 corrective
            self.features.add("TEXTW")
            buf = self._string_ptr(e.args[0], prefer=SCRATCH_BUFFERS[1])
            w.emit("    call rt_text_width")
            if buf is not None:
                self._scratch_release(buf)
            return
        if e.name in ("BITMAPW", "BITMAPH"):  # M12: the bitmap record's current size
            offset = 4 if e.name == "BITMAPW" else 6
            if self.program.variables[e.args[0].name].type == "BITMAPREF":  # M13: a parameter
                w.emit(f"    ld hl,(var_{mangle(e.args[0].name)})", f"    ld de,{offset}", "    add hl,de",
                       "    ld a,(hl)", "    inc hl", "    ld h,(hl)", "    ld l,a")
            else:
                w.emit(f"    ld hl,(var_{mangle(e.args[0].name)}+{offset})")
            return
        if e.name == "PAGEWIDTH":  # M12 printing
            self.features.update(("PAGE", "FIO"))
            buf = self._string_ptr(e.args[0], prefer=SCRATCH_BUFFERS[1])
            w.emit("    call rt_pg_width")
            if buf is not None:
                self._scratch_release(buf)
            return
        if e.name == "POINT":  # M12
            self.features.add("POINT")
            self.expr(e.args[0])
            w.emit("    push hl")
            self.expr(e.args[1])
            w.emit("    ex de,hl", "    pop hl", "    call rt_point")
            return
        if e.name == "SECONDS":  # M11 corrective
            self.features.add("CLOCK")
            w.emit("    call rt_seconds")
            return
        if e.name == "CLOCKTICKS":  # M13 corrective
            self.features.add("CLOCKTICKS")
            w.emit("    call rt_clockticks")
            return
        if e.name == "KEYDOWN":  # M13: bios_keystate of a set-2 scan code
            self.features.add("KEYDOWN")
            self.expr(e.args[0])
            w.emit("    push hl", f"    ld hl,{e.line}", "    ld (rt_err_line),hl", "    pop hl",
                   "    call rt_keydown")
            return
        if e.name in ("VAL", "ASC"):  # M5b
            self.features.add(e.name)
            buf = self._string_ptr(e.args[0], prefer=SCRATCH_BUFFERS[1])
            w.emit("    call rt_val" if e.name == "VAL" else "    call rt_asc")
            if buf is not None:
                self._scratch_release(buf)
            return
        if e.name == "INSTR":  # M5b: INSTR([start,] a$, b$)
            self.features.add("INSTR")
            *start, hay, needle = e.args
            hay_buf = self._string_ptr(hay)
            w.emit("    push hl")
            needle_buf = self._string_ptr(needle)
            w.emit("    push hl")
            if not start:
                w.emit("    ld hl,0")
            elif isinstance(start[0], ast.IntLiteral):
                w.emit(f"    ld hl,{start[0].value - 1}")
            else:
                self.uses_slice = True  # rt_chk_start (substring position error)
                self.expr(start[0])
                w.emit("    call rt_chk_start")
            w.emit("    ld b,h", "    ld c,l", "    pop de", "    pop hl", "    call rt_instr")
            for buf in (needle_buf, hay_buf):
                if buf is not None:
                    self._scratch_release(buf)
            return
        if e.name == "CINT":  # M7: REAL rounded to INTEGER
            if getattr(e.args[0], "typ", None) == "REAL":
                self.real(e.args[0])
                w.emit("    call rt_fcint")
            else:
                self.expr(e.args[0])
            return
        if e.name == "SGN" and getattr(e.args[0], "typ", None) == "REAL":  # M7
            self.real(e.args[0])
            w.emit("    call rt_fsgn")
            return
        if e.name == "ISNUM":  # M7
            self.features.add("REAL")
            buf = self._string_ptr(e.args[0])
            w.emit("    call rt_fisnum")
            if buf is not None:
                self._scratch_release(buf)
            return
        if e.name in ("ABS", "SGN"):  # M7 (INTEGER)
            self.expr(e.args[0])
            done = w.new_label("cgabs")
            if e.name == "ABS":  # -32768 stays -32768 (wrapping, LANGUAGE-SPEC §2)
                w.emit("    bit 7,h", f"    jp z,{done}", "    xor a", "    ld de,0", "    ex de,hl",
                       "    sbc hl,de", f"{done}:")
            else:
                w.emit("    ld a,h", "    or l", f"    jp z,{done}", "    bit 7,h", "    ld hl,1",
                       f"    jp z,{done}", "    ld hl,-1", f"{done}:")
            return
        if e.name in ("MIN", "MAX", "SHL", "SHR"):  # M7: DE = first, HL = second
            self.features.add("IMATH")
            self.expr(e.args[0])
            w.emit("    push hl")
            self.expr(e.args[1])
            w.emit("    pop de", f"    call rt_i{e.name.lower()}")
            return
        if e.name == "TEXTSAME":  # M10: two buffers, byte for byte
            self.features.update(("TEXT", "TXRANGE"))
            w.emit(f"    ld hl,var_{mangle(e.args[1].name)}", "    ld (rt_tx_src),hl",
                   f"    ld hl,var_{mangle(e.args[0].name)}", "    call rt_text_same")
            return
        if e.name in ("TEXTLINES", "TEXTCOL", "TEXTCHANGED", "TEXTFREE", "TEXTSIZE", "TEXTLEN",
                      "TEXTFIND"):  # M9 Stage C
            self.features.add("TEXT")
            record = f"var_{mangle(e.args[0].name)}"
            if e.name == "TEXTLINES":
                w.emit(f"    ld hl,({record}+8)")
            elif e.name == "TEXTCOL":
                w.emit(f"    ld hl,({record}+16)")
            elif e.name == "TEXTCHANGED":
                w.emit(f"    ld hl,({record}+10)", "    ld h,0")
            elif e.name in ("TEXTFREE", "TEXTSIZE"):
                w.emit(f"    ld hl,{record}",
                       f"    call {'rt_text_free' if e.name == 'TEXTFREE' else 'rt_text_used'}")
            else:
                held = self._text_args(e.args[1:])
                cells = ("rt_tx_n",) if e.name == "TEXTLEN" else ("rt_tx_str", "rt_tx_n", "rt_tx_c")
                for cell in reversed(cells):
                    w.emit("    pop hl", f"    ld ({cell}),hl")
                w.emit(f"    ld hl,{record}", f"    call {'rt_text_len' if e.name == 'TEXTLEN' else 'rt_text_find'}")
                for buf in held:
                    self._scratch_release(buf)
            return
        if e.name in ("MOUSEX", "MOUSEY", "MOUSEEVENT", "KEYCODE", "KEYSHIFT"):  # M9
            cell = {"MOUSEX": "rt_cv_mx", "MOUSEY": "rt_cv_my", "MOUSEEVENT": "rt_cv_mev",
                    "KEYCODE": "rt_cv_key", "KEYSHIFT": "rt_cv_shift"}[e.name]
            w.emit(f"    ld hl,({cell})")
            return
        if e.name in ("DBFIND", "DBNEXTID"):  # M10
            table = self._db_table(e.args[0].name)
            if e.name == "DBFIND":
                w.emit(f"    ld hl,{e.line}", "    ld (rt_err_line),hl")
                self.expr(e.args[2])
                w.emit("    push hl")
                self.expr(e.args[1])
                w.emit("    ld (rt_db_n),hl", "    pop hl", "    ld (rt_db_k),hl")
            w.emit(f"    ld hl,{table}", f"    call rt_db_{e.name[2:].lower()}")
            return
        if e.name == "DBRECOVERED":  # M10: which file the last DB LOAD used
            self.features.add("DB")
            w.emit("    ld hl,(rt_db_recov)")
            return
        if e.name == "IOERR":  # M7: the last file operation's outcome
            self.features.add("FIO")
            w.emit("    ld hl,(rt_fio_err)")
            return
        if e.name == "EOF":  # M7: TRUE unless channel n has a line left to read
            self.features.add("FIO")
            w.emit(f"    ld c,{e.args[0].value}", "    call rt_fio_eof")
            return
        if e.name == "RND":  # M7: 1..n
            self.features.update(("IMATH", "DIV"))
            self.expr(e.args[0])
            w.emit("    call rt_rnd")
            return
        raise SourceError(
            e.line,
            e.column,
            f"{e.name} does not produce an INTEGER/BOOLEAN value usable here",
        )

    def _string_ptr(self, e: ast.Expr, prefer: str | None = None) -> str | None:
        """HL = pointer to STRING *e*: in place for a literal or variable,
        otherwise built in a pool buffer, which is returned (still held; the
        caller releases it after use)."""
        w = self.w
        if isinstance(e, ast.StrLiteral):
            w.emit(f"    ld hl,{w.pool_label(e.value)}")
            return None
        if isinstance(e, ast.Var):
            w.emit(f"    ld hl,var_{mangle(e.name)}")
            return None
        if isinstance(e, ast.Index):  # M6 Phase 2: the element in place
            self._elem_addr(e.name, e.index)
            return None
        buf = self._scratch_acquire(e, prefer=prefer)
        self._string_operand(e, buf)
        return buf

    def _is_string_expr(self, e: ast.Expr) -> bool:
        if isinstance(e, ast.StrLiteral):
            return True
        if isinstance(e, (ast.Var, ast.Index)):
            return self.program.variables[e.name].type == "STRING"
        if isinstance(e, ast.Call):
            return e.name in _STRING_FUNCTIONS
        if isinstance(e, ast.Binary) and e.op == "+":  # M5a concatenation
            return self._is_string_expr(e.left)
        return False

    # ------------------------------------------------------- string append/slice
    def _string_operand(self, e: ast.Expr, scratch: str) -> None:
        """Leave in HL a pointer to the NUL-terminated text of STRING *e*.

        Literals and variables are used in place; computed values are built
        in *scratch* (128 bytes) under the rt_put guard.

        The caller owns *scratch* (taken from the pool) until it has used the
        result; anything nested inside the build takes other pool buffers.
        """
        w = self.w
        if isinstance(e, ast.StrLiteral):
            w.emit(f"    ld hl,{w.pool_label(e.value)}")
        elif isinstance(e, ast.Var):
            w.emit(f"    ld hl,var_{mangle(e.name)}")
        elif isinstance(e, ast.Index):  # M6 Phase 2: the element in place
            self._elem_addr(e.name, e.index)
        else:
            self._begin_string(scratch, SCRATCH_STRING_MAX + 1)
            self._append_parts(e)
            w.emit("    xor a", "    ld (de),a", f"    ld hl,{scratch}")

    def _append_parts(self, e: ast.Expr) -> None:
        """Append the text of a STRING expression at the current DE position
        (rt_str_copy/rt_append_int advance DE past the written bytes)."""
        w = self.w
        if isinstance(e, ast.Binary) and e.op == "+":
            self._append_parts(e.left)
            self._append_parts(e.right)
        elif isinstance(e, ast.StrLiteral):
            label = w.pool_label(e.value)
            size = len(e.value.encode("utf-8"))
            w.emit(f"    ld hl,{label}", f"    ld bc,{size}", "    call rt_str_copy")
        elif isinstance(e, ast.Var):
            capacity = self.program.variables[e.name].capacity
            w.emit(
                f"    ld hl,var_{mangle(e.name)}",
                f"    ld bc,{capacity}",
                "    call rt_str_copy",
            )
        elif isinstance(e, ast.Index):
            # M6 Phase 2: an element; its index may build strings, so the
            # build position and limit are saved around it (as for STR$).
            capacity = self.program.variables[e.name].capacity
            w.emit("    push de", "    ld hl,(rt_dst_end)", "    push hl")
            self._elem_addr(e.name, e.index)
            w.emit("    pop de", "    ex de,hl", "    ld (rt_dst_end),hl", "    ex de,hl",
                   "    pop de", f"    ld bc,{capacity}", "    call rt_str_copy")
        elif isinstance(e, ast.Call) and e.name == "STR$" and getattr(e.args[0], "typ", None) == "REAL":
            # M7: the REAL's text (rt_fstr appends it at DE through rt_put)
            w.emit("    push de", "    ld hl,(rt_dst_end)", "    push hl")
            self.real(e.args[0])
            w.emit("    pop de", "    ex de,hl", "    ld (rt_dst_end),hl", "    ex de,hl",
                   "    pop de", "    call rt_fstr")
        elif isinstance(e, ast.Call) and e.name == "STR$":
            # The argument may itself build a string (LEN of a substring) and
            # so move the active destination: save DE and rt_dst_end around it.
            w.emit("    push de", "    ld hl,(rt_dst_end)", "    push hl")
            self.expr(e.args[0])
            w.emit(
                "    pop de",
                "    ex de,hl",
                "    ld (rt_dst_end),hl",
                "    ex de,hl",  # HL = value again
                "    pop de",
                "    call rt_append_int",
            )
        elif isinstance(e, ast.Call) and e.name == "CHR$":
            # M5b: one character, code checked 1..255 at run time; the code
            # expression may build strings, so the build position is saved.
            self.features.add("CHR")
            w.emit("    push de", "    ld hl,(rt_dst_end)", "    push hl")
            self.expr(e.args[0])
            w.emit("    pop de", "    ex de,hl", "    ld (rt_dst_end),hl", "    ex de,hl",
                   "    pop de", "    call rt_chr_put")
        elif isinstance(e, ast.Call) and e.name in ("UCASE$", "LCASE$"):
            # M5c: append the argument, then change the case of exactly the
            # bytes just written ([start, DE)) in place; DE is kept.
            self.features.add("CASE")
            w.emit("    push de")
            self._append_parts(e.args[0])
            w.emit("    pop hl", f"    call {'rt_ucase' if e.name == 'UCASE$' else 'rt_lcase'}")
        elif isinstance(e, ast.Call) and e.name in ("TRIM$", "LTRIM$", "RTRIM$"):
            # M7: append the argument, then trim the bytes just written in
            # place ([start, DE)); DE moves back to the new end.
            # M11 (KI-64): the STRFN section also holds rt_repeat, which
            # reports a negative count through rt_err_substring (SLICE) and a
            # bad code through rt_err_chr (CHR); a program with TRIM$ and
            # nothing else that needs them did not assemble. No program that
            # assembled before changes (tests/test_m11_regressions.py).
            self.features.update(("STRFN", "CHR"))
            self.uses_slice = True
            w.emit("    push de")
            self._append_parts(e.args[0])
            w.emit("    pop hl", f"    call rt_{e.name[:-1].lower()}")
        elif isinstance(e, ast.Call) and e.name in ("SPACE$", "STRING$"):
            # M7: n copies of a character (code checked 1..255), through
            # rt_put; the arguments may build strings, so the build position
            # and limit are saved around them.
            self.features.update(("STRFN", "CHR"))
            self.uses_slice = True  # rt_err_substring for a negative count
            w.emit("    push de", "    ld hl,(rt_dst_end)", "    push hl")
            self.expr(e.args[0])
            w.emit("    push hl")
            if e.name == "SPACE$":
                w.emit("    ld hl,32")
            else:
                self.expr(e.args[1])
            w.emit("    ld b,h", "    ld c,l", "    pop hl", "    pop de", "    ex de,hl",
                   "    ld (rt_dst_end),hl", "    ex de,hl", "    pop de", "    call rt_repeat")
        elif isinstance(e, ast.Call) and e.name == "TEXTGET$":
            # M9: appended at DE through rt_put; the arguments may build
            # strings, so the build position and limit are saved around them.
            self.features.add("TEXT")
            w.emit("    push de", "    ld hl,(rt_dst_end)", "    push hl")
            held = self._text_args(e.args[1:])
            for cell in ("rt_tx_k", "rt_tx_c", "rt_tx_n"):
                w.emit("    pop hl", f"    ld ({cell}),hl")
            w.emit("    pop hl", "    ld (rt_dst_end),hl", "    pop de",
                   f"    ld hl,var_{mangle(e.args[0].name)}", "    call rt_text_get")
            for buf in held:
                self._scratch_release(buf)
        elif isinstance(e, ast.Call) and e.name in ("LEFT$", "MID$", "RIGHT$"):
            self._slice(e)
        else:
            raise AssertionError(f"not a STRING part: {type(e).__name__}")

    def _slice(self, e: ast.Call) -> None:
        """LEFT$/MID$/RIGHT$ of a STRING variable or literal, appended at DE.

        MID$/RIGHT$ skip via rt_str_skip (which preserves DE and advances HL
        to the slice start) and copy from that advanced HL — the POC-verified
        pb_slice_append shape (POC/ui_codegen.py); there is deliberately no
        source reload after the skip. Counts bound how much is *read*; the
        destination is protected by rt_put (M2.1).
        """
        w = self.w
        src = e.args[0]
        if not (isinstance(src, (ast.Var, ast.StrLiteral))
                and all(isinstance(a, ast.IntLiteral) for a in e.args[1:])):
            self._slice_general(e)
            return
        if isinstance(src, ast.Var):
            src_label = f"var_{mangle(src.name)}"
        else:
            src_label = w.pool_label(src.value)
        if e.name == "LEFT$":
            count = e.args[1].value
            w.emit(f"    ld hl,{src_label}", f"    ld bc,{count}", "    call rt_str_copy")
        elif e.name == "MID$":
            skip = e.args[1].value - 1
            count = e.args[2].value
            w.emit(
                f"    ld hl,{src_label}",
                f"    ld bc,{skip}",
                "    call rt_str_skip",
                f"    ld bc,{count}",
                "    call rt_str_copy",
            )
        else:  # RIGHT$
            count = e.args[1].value
            ok = w.new_label("cgright")
            w.emit(
                # Length math clobbers DE (the append destination): save it.
                "    push de",
                f"    ld hl,{src_label}",
                "    call rt_str_len",
                "    ld h,b",
                "    ld l,c",
                f"    ld de,{count}",
                "    or a",
                "    sbc hl,de",
                "    ld b,h",
                "    ld c,l",
                f"    jp nc,{ok}",
                "    ld bc,0",
                f"{ok}:",
                "    pop de",
                f"    ld hl,{src_label}",
                "    call rt_str_skip",
                f"    ld bc,{count}",
                "    call rt_str_copy",
            )


    def _slice_general(self, e: ast.Call) -> None:
        """M5a: LEFT$/MID$/RIGHT$ with a computed source and/or run-time
        positions and counts, appended at DE.

        Order: save the build position (DE, rt_dst_end); obtain the source
        pointer (a computed source is built, whole, in a pool buffer held
        until the slice is copied); evaluate the integer arguments, checking
        each computed one at run time (count >= 0, MID$ start >= 1; else the
        reported substring runtime error); then restore the build position
        and copy. Nothing is written to the destination before every
        argument is known, so arguments may read the destination itself.
        """
        w = self.w
        src = e.args[0]
        w.emit("    push de", "    ld hl,(rt_dst_end)", "    push hl")
        buf = None
        if isinstance(src, ast.Var):
            w.emit(f"    ld hl,var_{mangle(src.name)}")
        elif isinstance(src, ast.StrLiteral):
            w.emit(f"    ld hl,{w.pool_label(src.value)}")
        else:
            buf = self._scratch_acquire(src)
            self._string_operand(src, buf)
        w.emit("    push hl")
        if e.name == "MID$":
            self._slice_arg(e.args[1], "rt_chk_start")  # leaves start - 1
            self._slice_arg(e.args[2], "rt_chk_count")
            w.emit("    pop hl", "    ld (rt_slc_count),hl", "    pop bc")
        else:
            self._slice_arg(e.args[1], "rt_chk_count")
            w.emit("    pop bc")
        w.emit(
            "    pop hl",  # source
            "    ex de,hl",
            "    pop hl",
            "    ld (rt_dst_end),hl",
            "    ex de,hl",
            "    pop de",
        )
        call = {"LEFT$": "rt_str_copy", "MID$": "rt_slice_mid", "RIGHT$": "rt_slice_right"}
        w.emit(f"    call {call[e.name]}")
        if buf is not None:
            self._scratch_release(buf)

    def _slice_arg(self, arg: ast.Expr, check: str) -> None:
        """Evaluate a substring position/count to the stack. A literal was
        checked by semantics; anything else is checked at run time."""
        self.uses_slice = True
        w = self.w
        if isinstance(arg, ast.IntLiteral):
            value = arg.value - 1 if check == "rt_chk_start" else arg.value
            w.emit(f"    ld hl,{value}")
        else:
            self.expr(arg)
            w.emit(f"    call {check}")
        w.emit("    push hl")


_REAL_OPS = {"+": "rt_fadd", "-": "rt_fsub", "*": "rt_fmul", "/": "rt_fdiv", "^": "rt_fpow"}
_REAL_CALLS = {"SQR": "rt_fsqr", "SIN": "rt_fsin", "COS": "rt_fcos", "TAN": "rt_ftan",
               "ATN": "rt_fatn", "LOG": "rt_flog", "EXP": "rt_fexp", "INT": "rt_ffloor",
               "FIX": "rt_ffix", "ABS": "rt_fabs", "REAL": None}


def constant_step(e: ast.Expr) -> int:
    """A FOR STEP: an INTEGER constant (semantics-enforced)."""
    if isinstance(e, ast.Unary):
        return -e.operand.value if e.op == '-' else e.operand.value
    return e.value


def _concat_parts(e: ast.Expr) -> list[ast.Expr]:
    """The parts of a STRING expression, left to right, through '+'."""
    if isinstance(e, ast.Binary) and e.op == "+":
        return _concat_parts(e.left) + _concat_parts(e.right)
    return [e]


def _reads_var(e: ast.Expr, name: str) -> bool:
    """True if evaluating *e* reads variable *name* anywhere."""
    if isinstance(e, ast.Var):
        return e.name == name
    if isinstance(e, ast.Index):
        return e.name == name or _reads_var(e.index, name)
    if isinstance(e, ast.Call):
        return any(_reads_var(a, name) for a in e.args)
    if isinstance(e, ast.Unary):
        return _reads_var(e.operand, name)
    if isinstance(e, ast.Binary):
        return _reads_var(e.left, name) or _reads_var(e.right, name)
    return False


def _may_fail(e: ast.Expr) -> bool:
    """True if evaluating *e* may raise an M5b runtime error (division by
    zero, VAL out of range, CHR$ code, INSTR start), so the statement must
    record its line in rt_err_line."""
    if isinstance(e, ast.Index):  # M6 Phase 2: index out of range
        return True
    if getattr(e, "typ", None) == "REAL":  # M7: overflow, division by zero, domains
        return True
    if isinstance(e, ast.Binary):
        return e.op in ("/", "MOD") or _may_fail(e.left) or _may_fail(e.right)
    if isinstance(e, ast.Call):
        return e.name in ("VAL", "CHR$", "INSTR", "RND", "SHL", "SHR", "SPACE$", "STRING$") \
            or any(_may_fail(a) for a in e.args)
    if isinstance(e, ast.Unary):
        return _may_fail(e.operand)
    return False


def _builds_string(e: ast.Expr) -> bool:
    """True if evaluating *e* writes string text (a STR$/substring call)."""
    if isinstance(e, ast.Call):
        return e.name in _STRING_FUNCTIONS or any(_builds_string(a) for a in e.args)
    if isinstance(e, ast.Index):
        return _builds_string(e.index)
    if isinstance(e, ast.Unary):
        return _builds_string(e.operand)
    if isinstance(e, ast.Binary):
        return _builds_string(e.left) or _builds_string(e.right)
    return False
