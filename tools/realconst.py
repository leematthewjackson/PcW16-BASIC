"""Generate the REAL constant tables of runtime/runtime.z80.asm (M7).

Run ``python3 tools/realconst.py`` and paste the output between the
"realconst.py begin/end" markers of the runtime. Every constant is the
5-byte REAL nearest to its exact value (pbas/real.py), computed from
high-precision decimal text, so the tables are reproducible and reviewable.
The Cody–Waite splits (LN2_HI, PIO2_HI) keep few significant bits, so that
n * HI is exact for every n the runtime uses.
"""
from __future__ import annotations

import sys
from fractions import Fraction
from math import factorial
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pbas.real import pack  # noqa: E402

PI = Fraction("3.14159265358979323846264338327950288419716939937510582097494")
LN2 = Fraction("0.693147180559945309417232121458176568075500134360255254120680")
SQRT3 = Fraction("1.73205080756887729352744634150587236694280525381038062805580")
SQRT_HALF = Fraction("0.707106781186547524400844362104849039284835937688474036588340")
TAN15 = 2 - SQRT3  # tan(pi/12)


def truncated(value: Fraction, bits: int) -> Fraction:
    """*value* with only its *bits* most significant bits kept."""
    scale = Fraction(2) ** (bits - (value.numerator.bit_length() - value.denominator.bit_length()))
    return Fraction(int(value * scale)) / scale


def line(label: str, value, comment: str) -> str:
    return f"{label}:\n    db {','.join(str(b) for b in pack(value))}  ; {comment}"


def table(label: str, values, comment: str) -> str:
    out = [f"{label}:  ; {comment}", f"    db {len(values)}"]
    out += [f"    db {','.join(str(b) for b in pack(v))}" for v in values]
    return "\n".join(out)


def main() -> None:
    ln2_hi = truncated(LN2, 22)
    pio2 = PI / 2
    pio2_hi = truncated(pio2, 16)
    parts = [
        "; realconst.py begin (generated by tools/realconst.py; do not edit by hand)",
        line("rt_fc_half", Fraction(1, 2), "0.5"),
        line("rt_fc_inv_ln2", 1 / LN2, "1 / ln 2"),
        line("rt_fc_ln2_hi", ln2_hi, "ln 2, high 22 bits"),
        line("rt_fc_ln2_lo", LN2 - ln2_hi, "ln 2 - LN2_HI"),
        line("rt_fc_exp_max", Fraction("88.0296919"), "above: EXP overflows"),
        line("rt_fc_exp_min", Fraction("-89.4"), "below: EXP underflows to 0"),
        line("rt_fc_sqrt_half", SQRT_HALF, "sqrt(1/2)"),
        line("rt_fc_two_pi", 2 / PI, "2 / pi"),
        line("rt_fc_pio2_hi", pio2_hi, "pi/2, high 16 bits"),
        line("rt_fc_pio2_lo", pio2 - pio2_hi, "pi/2 - PIO2_HI"),
        line("rt_fc_trig_max", Fraction(51000), "largest |x| for SIN/COS/TAN"),
        line("rt_fc_pio2", pio2, "pi/2"),
        line("rt_fc_pio6", PI / 6, "pi/6"),
        line("rt_fc_sqrt3", SQRT3, "sqrt 3"),
        line("rt_fc_tan15", TAN15, "tan(pi/12)"),
        table("rt_fc_exp_poly", [Fraction(1, factorial(k)) for k in range(11, -1, -1)],
              "exp(r) = sum r^k / k!, k = 11..0 (Horner)"),
        table("rt_fc_log_poly", [Fraction(1, 2 * k + 1) for k in range(7, -1, -1)],
              "ln m = 2z * sum w^k / (2k+1), w = z^2, k = 7..0"),
        table("rt_fc_sin_poly", [Fraction((-1) ** k, factorial(2 * k + 1)) for k in range(6, -1, -1)],
              "sin r = r * sum (-1)^k w^k / (2k+1)!, w = r^2, k = 6..0"),
        table("rt_fc_cos_poly", [Fraction((-1) ** k, factorial(2 * k)) for k in range(7, -1, -1)],
              "cos r = sum (-1)^k w^k / (2k)!, k = 7..0"),
        table("rt_fc_atn_poly", [Fraction((-1) ** k, 2 * k + 1) for k in range(8, -1, -1)],
              "atn a = a * sum (-1)^k w^k / (2k+1), k = 8..0"),
        "; realconst.py end",
    ]
    print("\n".join(parts))


if __name__ == "__main__":
    main()
